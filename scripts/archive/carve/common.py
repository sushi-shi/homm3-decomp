#!/usr/bin/env python3
"""homm3.carve.common - carve-side paths, intake stamp, TSV conventions.

The shared primitives (repo paths, the pinned-image hash gate, provenance)
live in homm3.core.common and are re-exported here so carve stages keep
their imports unchanged. What stays HERE is carve-specific: the
build/carve/ workspace, the target.json intake stamp, the sanitized
llvm-objdump working copy, the vendored-reader load_image, and the TSV
read/write conventions.

TSV convention shared by all stages: `#` provenance lines (generator, exe
sha, date), then a tab-separated header, then rows. RVAs are 0x%x, sizes
decimal.
"""
from __future__ import annotations

import datetime
import json
from pathlib import Path

from homm3.core.common import (  # noqa: F401  (re-exports for carve stages)
    EVIDENCE_DIR, EXE_CANDIDATES, HOMM3_DIR, IMAGE_BASE, TARGET_SHA256,
    TARGET_SIZE, die, gate_exe, provenance, resolve_exe, sha256_of,
)

CARVE_DIR = HOMM3_DIR / "build/carve"
TARGET_JSON = CARVE_DIR / "target.json"

SANITIZED_EXE = CARVE_DIR / "HEROES3.llvm-objdump.exe"
_LOAD_CONFIG_INDEX = 10


def sanitized_exe(gated_path: Path) -> Path:
    """A working copy llvm-objdump will accept, under gitignored build/carve/.

    The retail linker put the load-config directory at RVA 0x2a0 - inside the
    PE headers, below the first section - and llvm-objdump 21 refuses to open
    such an image at all. The copy differs from retail in exactly the 8 bytes
    of data-directory[10] (zeroed); every RVA, section and code byte is
    identical, so it is valid ONLY as a disassembly substrate, never as
    evidence. Callers must pass an already sha-gated path.
    """
    data = bytearray(gated_path.read_bytes())
    pe = int.from_bytes(data[0x3C:0x40], "little")
    entry = pe + 24 + 96 + _LOAD_CONFIG_INDEX * 8
    data[entry:entry + 8] = b"\0" * 8
    CARVE_DIR.mkdir(parents=True, exist_ok=True)
    if not (SANITIZED_EXE.is_file() and SANITIZED_EXE.read_bytes() == bytes(data)):
        SANITIZED_EXE.write_bytes(bytes(data))
    return SANITIZED_EXE


def intake() -> dict:
    """S0: resolve + gate the exe, stamp target.json. Idempotent; every stage
    calls this so no stage can run against an unpinned image."""
    exe = resolve_exe()
    info = gate_exe(exe)
    from homm3.carve.find_relocs import Image
    image = Image(str(exe))
    info["sections"] = [
        {"name": s.name, "rva": s.rva, "size": s.size, "mapped": s.mapped,
         "raw_offset": s.raw_offset, "executable": s.executable}
        for s in image.sections]
    info["generated"] = datetime.date.today().isoformat()
    CARVE_DIR.mkdir(parents=True, exist_ok=True)
    TARGET_JSON.write_text(json.dumps(info, indent=2) + "\n")
    return info


def load_image():
    """The vendored PE reader over the gated exe - the package's only one.

    Reads the sanitized working copy (see sanitized_exe) so the vendored
    code_sites channel can shell out to llvm-objdump on image.path."""
    from homm3.carve.find_relocs import Image
    info = intake()
    work = sanitized_exe(Path(info["path"]))
    info["sanitized_path"] = str(work)
    return Image(str(work)), info


MANUAL_BANNER = (
    "# MANUALLY MANAGED - this file was INITIALLY GENERATED by homm3.carve\n"
    "# (provenance below) and is hand-owned after admission: boundary\n"
    "# corrections are edited directly into these rows; do not regenerate\n"
    "# over hand edits.\n")


def write_tsv(path: Path, generator: str, header: list[str], rows,
              extra: list[str] | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as fh:
        for line in provenance(generator, extra):
            fh.write(line + "\n")
        fh.write("\t".join(header) + "\n")
        for row in rows:
            fh.write("\t".join(str(cell) for cell in row) + "\n")
    return path


def read_tsv(path: Path) -> list[dict]:
    """Rows as dicts; `#` lines and blanks skipped; first data line is the header."""
    header = None
    rows = []
    for line in Path(path).read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cells = line.split("\t")
        if header is None:
            header = cells
            continue
        rows.append(dict(zip(header, cells)))
    if header is None:
        die(f"{path}: empty TSV")
    return rows


def need(path: Path, stage: str) -> Path:
    if not Path(path).is_file():
        die(f"missing {path} - run `python3 -m homm3.carve {stage}` first")
    return path
