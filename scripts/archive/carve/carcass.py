#!/usr/bin/env python3
"""homm3.carve.carcass - admit the source carcass: src/ + include/.

One .cpp per GAME compiland (vendored zlib modules stay in vendor/), the
functions in link order with their recovered signatures, and one header per
TU carrying the same prototypes grouped by class. Everything a file claims
is evidence-tiered exactly like the game tree it is materialized from:

  VA(0x<va>, 0x<size>)     the definition is tied to the PINNED retail
                           image (dcmap role recorded alongside); addresses
                           are ABSOLUTE VAs (base 0x400000) per the v2
                           contract in include/va.h, and compile out under
                           VC6. A later phase re-derives the label map from
                           these annotations every build
                           (source-as-authority).
  DC_ONLY(0x<off>, 0x<cb>) the proc exists in the Dreamcast build only so
                           far - no retail tie yet. Never a VA claim.

Prototypes and FILE:LINE are Dreamcast CodeView evidence; class layouts are
NOT fabricated from them - headers keep prototypes as comments until a
layout is independently recovered for the retail image (attempt-1's vetted
layouts remain a quarry, port plan P4.2).

Compiler-synthesized `scalar/vector deleting destructor' symbols are KEPT
in src/ deliberately (user decision 2026-08-04): CodeView attributes them
to the exact line of the destructor definition they were synthesized from
(measured: ~T and its deleting dtor share the same file:line), so they are
one source definition emitting two symbols - dropping the row would lose a
real definition-site anchor. Only the nameless `$`-thunks are omitted.

The stage is an ADMISSION: src/ and include/ are hand-owned after this
generation. It refuses to overwrite an existing src/ or include/ unless
--force is given.
"""
from __future__ import annotations

import csv
import re
import sys
from collections import defaultdict

from homm3.carve import common
from homm3.carve.names import DUMP, Dump

SRC_DIR = common.HOMM3_DIR / "src"
INC_DIR = common.HOMM3_DIR / "include"
DC_MAP = common.EVIDENCE_DIR / "retail-dc-name-map.csv"
IMAGE_BASE = 0x400000

STAMP = ("HAND-OWNED after admission - INITIALLY GENERATED by "
         "`python3 -m homm3.carve carcass`")


def load_csv(path):
    if not path.is_file():
        return []
    with path.open() as fh:
        return list(csv.DictReader(
            line for line in fh if not line.startswith("#")))


def main(argv=None) -> int:
    argv = list(argv or [])
    force = "--force" in argv
    for target in (SRC_DIR, INC_DIR):
        if target.exists() and any(target.iterdir()) and not force:
            common.die(f"{target} already exists and is hand-owned - "
                       "rerun with --force only if you mean to regenerate")

    print("[carve carcass] parsing Dreamcast CodeView dump ...", flush=True)
    dump = Dump(DUMP.read_text(errors="replace"))
    procs = sorted((p for p in dump.procs if p["cb"] > 0),
                   key=lambda p: p["offset"])
    tie = {int(r["dc_offset"], 16): (int(r["rva"], 16), r["role"])
           for r in load_csv(DC_MAP)}
    functions = {int(r["rva"], 16): int(r["size"]) for r in common.read_tsv(
        common.need(common.CARVE_DIR / "functions.tsv", "audit"))}

    modules = []
    by_module = defaultdict(list)
    for p in procs:
        if p["module"] not in by_module:
            modules.append(p["module"])
        by_module[p["module"]].append(p)
    modules.sort(key=lambda m: by_module[m][0]["offset"])

    def main_source(plist):
        from collections import Counter
        files = Counter(p["file"] for p in plist
                        if p["file"] and not p["file"].lower().endswith(".h"))
        return files.most_common(1)[0][0] if files else ""

    SRC_DIR.mkdir(exist_ok=True)
    INC_DIR.mkdir(exist_ok=True)
    stale = SRC_DIR / "rva.h"
    if stale.exists():
        stale.unlink()  # v1 contract header, superseded by include/va.h

    used = set()
    n_src = n_tied = n_dconly = n_thunks = n_vendor = 0
    for module in modules:
        plist = by_module[module]
        source = main_source(plist)
        if "zlib113" in source.lower():
            n_vendor += 1
            continue  # vendored: vendor/zlib-1.1.3 owns these TUs
        base = source.rsplit("\\", 1)[-1].rsplit("/", 1)[-1] \
            or module.replace(".obj", ".cpp")
        stem = re.sub(r"[^A-Za-z0-9_.-]", "_", base)
        if stem.lower() in used:
            stem = f"{module.rsplit('.', 1)[0]}_{stem}"
        used.add(stem.lower())
        header = stem.rsplit(".", 1)[0] + ".h"

        real = [p for p in plist if "$" not in p["name"]]
        thunks = len(plist) - len(real)
        n_thunks += thunks

        src_lines = [
            f"// {stem} - {source or module} (compiland {module})",
            f"// {STAMP}; prototypes are Dreamcast CodeView evidence.",
            f"// {len(real)} functions in link order"
            + (f"; {thunks} compiler-generated $-thunks omitted"
               if thunks else "") + ".",
            "#include <va.h>",
            f'// #include "{header}"',
            "",
        ]
        by_class = defaultdict(list)
        for p in real:
            sig = dump.signature(p) or p["name"]
            where = f"{p['file']}:{p['line']}" if p["file"] else module
            cls = p["name"].split("::", 1)[0] if "::" in p["name"] else ""
            by_class[cls].append((p, sig, where))
            src_lines.append(f"// {where}")
            if p["offset"] in tie:
                rva, role = tie[p["offset"]]
                size = functions.get(rva, 0)
                src_lines.append(f"VA(0x{IMAGE_BASE + rva:08x}, 0x{size:X})"
                                 f"  // {role}, dc 0x{p['offset']:x}")
                n_tied += 1
            else:
                src_lines.append(f"DC_ONLY(0x{p['offset']:x}, "
                                 f"0x{p['cb']:X})")
                n_dconly += 1
            src_lines += [sig, "{", "    // @stub", "}", ""]
        (SRC_DIR / stem).write_text("\n".join(src_lines) + "\n")
        n_src += 1

        guard = "HOMM3_" + re.sub(r"[^A-Za-z0-9]", "_", header).upper()
        inc_lines = [
            f"// {header} - prototypes of {stem} (compiland {module})",
            f"// {STAMP}.",
            "// Class layouts are NOT fabricated from method symbols;",
            "// prototypes stay comments until a retail layout is proven.",
            f"#ifndef {guard}",
            f"#define {guard}",
            "",
        ]
        for cls in sorted(by_class):
            inc_lines.append(f"// --- {cls or 'globals'} ---")
            for p, sig, where in by_class[cls]:
                inc_lines.append(f"// CODEVIEW({where}, dc 0x"
                                 f"{p['offset']:x}) {sig};")
            inc_lines.append("")
        inc_lines += [f"#endif  /* {guard} */"]
        (INC_DIR / header).write_text("\n".join(inc_lines) + "\n")

    print(f"[carve carcass] {n_src} TUs -> src/ + include/ "
          f"({n_vendor} vendored zlib modules left to vendor/)")
    print(f"  RVA-tied: {n_tied}; DC_ONLY: {n_dconly}; "
          f"$-thunks omitted: {n_thunks}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
