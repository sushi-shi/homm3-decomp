#!/usr/bin/env python3
"""Generate 60 canonical completion-worklist hypotheses for the terrain brush.

Retail 0x5b72f0 expands the painter completion worklist inside auto_ptr
cleanup. The primary point is copied before repair; the secondary point is
copied before erase(key), the repair predicate, and conditional painting.
Primary work generated by secondary painting is revisited before transitions.
The current brush expansion calls needsTerrainRepair where retail expands it
but retains getPackedCell and the horizontal/vertical gap helpers. Preserve
the canonical worklist and predicates; vary genuine snapshot lifetimes,
container nonempty tests and loop forms. No ownership workaround, pasted
helper, dummy work, false inline qualifier or pragma pin. Complete-only RMG
has no Dreamcast source counterpart.
"""
import argparse
import hashlib
import itertools
import json
from pathlib import Path

from homm3.core.common import HOMM3_DIR
from homm3.vc6 import _source, hypotheses

FUNCTION = "??1TRmgTerrainBrush@@QAE@XZ"
HELPER = "rmgTerrainPainter::finish"
SIGNATURE = "void rmgTerrainPainter::finish()"
PREDICATE = "rmgTerrainPainter::needsTerrainRepair"


def worklist(container, statements, condition, loop):
    query = container + (".size()" if condition == "size" else
                         ".size() != 0" if condition == "nonzero" else ".empty()")
    if condition == "empty":
        query = "!" + query
    if loop == "while":
        return ["while (" + query + ") {", *("    " + line for line in statements), "}"]
    if loop == "for":
        return ["for (; " + query + ";) {", *("    " + line for line in statements), "}"]
    if loop == "guarded_do":
        return ["if (" + query + ") {", "    do {",
                *("        " + line for line in statements), "    } while (" + query + ");", "}"]
    return ["for (;;) {", "    if (!(" + query + "))", "        break;",
            *("    " + line for line in statements), "}"]


def bodies(split_snapshots=False):
    snapshots = ("copy", "direct", "const_value", "const_reference", "assigned")
    if split_snapshots:
        choices = ((primary, secondary, condition, "while", (primary, secondary, condition, "while"))
                   for primary, secondary, condition in itertools.product(snapshots, snapshots, ("size", "empty")))
    else:
        choices = ((snapshot, snapshot, condition, loop, (snapshot, condition, loop))
                   for snapshot, condition, loop in itertools.product(
                       snapshots, ("size", "nonzero", "empty"), ("while", "for", "guarded_do", "break")))
    for primary, secondary, condition, loop, label in choices:
        lines = ["    do {"]
        for container in ("m_primaryPoints", "m_secondaryPoints"):
            snapshot = primary if container == "m_primaryPoints" else secondary
            value = "*" + container + ".begin()"
            if snapshot == "copy":
                visit = ["TRmgGridPoint point = " + value + ";"]
            elif snapshot == "direct":
                visit = ["TRmgGridPoint point(" + value + ");"]
            elif snapshot == "const_value":
                visit = ["const TRmgGridPoint point = " + value + ";"]
            elif snapshot == "const_reference":
                # Own a temporary snapshot: binding directly to the set node
                # would dangle after erase(key) and is not a valid candidate.
                visit = ["const TRmgGridPoint& point = TRmgGridPoint(" + value + ");"]
            else:
                visit = ["TRmgGridPoint point;", "point = " + value + ";"]
            if container == "m_primaryPoints":
                visit.append("repairTerrainPoint(point);")
            else:
                visit += ["m_secondaryPoints.erase(point);", "if (needsTerrainRepair(point))",
                          "    paintPoint(point);"]
            lines += ["        " + line for line in worklist(container, visit, condition, loop)]
        repeat = "!m_primaryPoints.empty()" if condition == "empty" else "m_primaryPoints.size()"
        if condition == "nonzero":
            repeat += " != 0"
        lines += ["    } while (" + repeat + ");", "    paintTransitions();"]
        yield "+".join(label), SIGNATURE + "\n{\n" + "\n".join(lines) + "\n}"


def make_manifest(source, split_snapshots=False):
    found = _source.find_definitions(source, HELPER)
    if len(found) != 1:
        raise ValueError("review the unique canonical painter completion helper")
    item = found[0]
    start = source.rfind("\n", 0, item.head) + 1
    original = source[start:item.body_close + 1]
    options = list(bodies(split_snapshots))
    if original not in {body for split in (False, True) for _, body in bodies(split)}:
        raise ValueError("review the painter worklist before rebasing the family")
    options.sort(key=lambda row: row[1] != original)
    evidence = __doc__
    if split_snapshots:
        evidence += ("\nFollow-up: vary primary and secondary snapshots independently across five lifetimes "
                     "and two nonempty tests (50 states). The coupled matrix often stopped expansion of "
                     "the entire completion helper; this separates its two real snapshot boundaries.")
    return dict(schema=1, unit="rmg_terrain", function=FUNCTION, evidence=evidence, axes=[dict(
        name="completion_worklist", find=original,
        options=[dict(name=name, replace=body) for name, body in options])])


def predicate_bodies():
    horizontal = "isHorizontalGap(point)"
    vertical = "isVerticalGap(point)"
    allows = "g_rmgTerrainRules[getTerrain(point)]->m_allowsSeparatedNeighbours"
    separated = "hasSeparatedNeighbours(point)"
    guard_tail = ["    if (" + allows + ")", "        return 0;", "    return " + separated + ";"]
    forms = {
        "combined": ["    if (" + horizontal + " || " + vertical + ")", "        return 1;", *guard_tail],
        "adjacent": ["    if (" + horizontal + ")", "        return 1;",
                     "    if (" + vertical + ")", "        return 1;", *guard_tail],
        "nested": ["    if (!" + horizontal + ") {", "        if (!" + vertical + ") {",
                   "            if (" + allows + ")", "                return 0;",
                   "            return " + separated + ";", "        }", "    }", "    return 1;"],
        "else_if": ["    if (" + horizontal + ")", "        return 1;",
                    "    else if (" + vertical + ")", "        return 1;",
                    "    else if (" + allows + ")", "        return 0;",
                    "    else", "        return " + separated + ";"],
        "named_horizontal": ["    unsigned char horizontal = " + horizontal + ";",
                             "    if (horizontal || " + vertical + ")", "        return 1;", *guard_tail],
        "conditional": ["    return " + horizontal + " ? 1", "        : " + vertical + " ? 1",
                        "        : " + allows + " ? 0", "        : " + separated + ";"],
    }
    signature = "unsigned char rmgTerrainPainter::needsTerrainRepair(const TRmgGridPoint& point)"
    for name, lines in forms.items():
        yield name, signature + "\n{\n" + "\n".join(lines) + "\n}"


def make_predicate_manifest(source, parent_labels):
    payload = make_manifest(source)
    axis = payload["axes"][0]
    choices = {name: dict(name=name, replace=body) for split in (False, True) for name, body in bodies(split)}
    if len(parent_labels) != 10 or len(set(parent_labels)) != 10 or any(name not in choices for name in parent_labels):
        raise ValueError("review ten unique completion parents")
    axis["options"] = [choices[name] for name in parent_labels]
    found = _source.find_definitions(source, PREDICATE)
    if len(found) != 1:
        raise ValueError("review the unique canonical repair predicate")
    item = found[0]
    start = source.rfind("\n", 0, item.head) + 1
    original = source[start:item.body_close + 1]
    options = list(predicate_bodies())
    if original not in {body for _, body in options}:
        raise ValueError("review the repair predicate before rebasing")
    options.sort(key=lambda row: row[1] != original)
    payload["axes"].append(dict(name="repair_predicate", find=original,
        options=[dict(name=name, replace=body) for name, body in options]))
    payload["evidence"] += ("\nFollow-up: cross ten retained completion parents with six short-circuit forms "
                            "of the existing canonical repair predicate. Keep horizontal/vertical/terrain/"
                            "separation query order, direct byte return and ordinary helper ownership; "
                            "all parents and a separate canonical baseline are recompiled.")
    return payload


def make_order_manifest(source, parents):
    payload = make_manifest(source)
    worklists = {name: body for split in (False, True) for name, body in bodies(split)}
    predicates = dict(predicate_bodies())
    if (len(parents) != 10 or len(set(parents)) != 10
            or any(work not in worklists or pred not in predicates for work, pred in parents)):
        raise ValueError("review ten unique worklist/predicate parents")
    groups = {}
    spans = {}
    for key, name, marker in (
            ("horizontal", "isHorizontalGap", "// Own-terrain checks share the predicates"),
            ("vertical", "isVerticalGap", None),
            ("repair", "needsTerrainRepair", "// The repeated four-check expansion")):
        signature = "unsigned char rmgTerrainPainter::" + name + "(const TRmgGridPoint& point)"
        found = [item for item in _source.find_definitions(source, "rmgTerrainPainter::" + name)
                 if source[source.rfind("\n", 0, item.head) + 1:item.body_open].strip() == signature]
        if len(found) != 1:
            raise ValueError("review the own-terrain helper " + name)
        item = found[0]
        start = source.rfind("\n", 0, item.head) + 1
        if marker:
            start = source.rfind(marker, 0, start)
            if start < 0:
                raise ValueError("review the helper evidence comment " + name)
        spans[key] = (start, item.body_close + 1)
        groups[key] = source[start:item.body_close + 1]
    keys = list(groups)
    ordered = sorted(keys, key=lambda key: spans[key][0])
    for left, right in zip(ordered, ordered[1:]):
        if source[spans[left][1]:spans[right][0]] != "\n\n":
            raise ValueError("review statements between the own-terrain helpers")
    original = source[spans[ordered[0]][0]:spans[ordered[-1]][1]]
    old_predicate = [body for body in predicates.values() if body in groups["repair"]]
    if len(old_predicate) != 1:
        raise ValueError("review the current repair predicate")
    options = []
    worklist_find = payload["axes"][0]["find"]
    for work, pred in parents:
        selected = dict(groups)
        selected["repair"] = selected["repair"].replace(old_predicate[0], predicates[pred])
        for order in itertools.permutations(keys):
            options.append(dict(name=work + "+" + pred + "+" + "+".join(order),
                replace="\n\n".join(selected[key] for key in order),
                extra_edits=[dict(find=worklist_find, replace=worklists[work])]))
    payload["axes"] = [dict(name="completion_predicate_order", find=original, options=options)]
    payload["evidence"] += ("\nFollow-up: cross ten worklist/predicate parents with all six orders of the "
                            "existing own-terrain horizontal, vertical and repair predicate definitions, "
                            "moving their evidence comments with them. Preserve one canonical definition "
                            "of every helper and recompile every parent plus the independent baseline.")
    return payload


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    follow_up = parser.add_mutually_exclusive_group()
    follow_up.add_argument("--predicate-from", type=Path, help="cross ten completed parents with six repair predicate forms")
    follow_up.add_argument("--helper-order-from", type=Path, help="cross ten joint worklist/predicate parents with six helper orders")
    follow_up.add_argument("--split-snapshots", action="store_true", help="cross primary/secondary snapshots independently in fifty states")
    args = parser.parse_args()
    source = (HOMM3_DIR / "src/rmg_terrain.cpp").read_text()
    parent_path = args.predicate_from or args.helper_order_from
    if parent_path:
        parent = json.loads(parent_path.read_text())
        if (parent.get("schema") != 1 or parent.get("unit") != "rmg_terrain" or parent.get("function") != FUNCTION
                or parent.get("source_sha256") != hashlib.sha256(source.encode()).hexdigest()):
            raise ValueError("review the completion parents against the current source")
        rows = [row for row in parent["results"] if not row["error"] and row["score"] is not None]
        if args.predicate_from:
            payload = make_predicate_manifest(source, [row["labels"]["completion_worklist"] for row in rows[:10]])
        else:
            payload = make_order_manifest(source, [(row["labels"]["completion_worklist"], row["labels"]["repair_predicate"])
                                                   for row in rows[:10]])
        payload["parent_results"] = str(parent_path.resolve())
    else:
        payload = make_manifest(source, args.split_snapshots)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2) + "\n")
    parsed = hypotheses.parse_manifest(args.output)
    print("generated", len(hypotheses.variants(parsed[4], parsed[5])), "unique source hypotheses ->", args.output)


if __name__ == "__main__":
    main()
