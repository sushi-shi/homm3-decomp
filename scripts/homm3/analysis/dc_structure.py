"""Materialize Dreamcast NB11 facts as annotated C++ and detailed JSON views.

The generated stubs are a browsing surface, not build inputs or recovered bodies.
No retail names or addresses are admitted by this exporter.
"""
from __future__ import annotations

from collections import Counter, defaultdict
from dataclasses import asdict
import json
from pathlib import Path
import re
import tempfile

from homm3.analysis import dc_asm, dc_lines, dreamcast
from homm3.core import common, inputs, nb11
from homm3.core.nb11_types import Types


GENERATOR = "homm3 dreamcast structure"
DEFAULT_OUTPUT = common.EVIDENCE_DIR / "dreamcast/structure"
SCHEMA = "homm3.dreamcast-structure.v1"
BANNER = (
    "// GENERATED by homm3 dreamcast structure; regenerate, do not edit.\n"
    "// Dreamcast RoE / WinCE SH4 reference; all dc addresses are .text offsets.\n"
    "// C++ browsing stubs: declarations and annotations, no recovered implementation.\n"
)


def _text(value) -> str:
    """Keep symbol/source text on one comment line."""
    return str(value).replace("\r", r"\r").replace("\n", r"\n")


def _span(start: int, end: int) -> str:
    return f"dc:0x{start:08x}..0x{end:08x}"


def _scope_ids(procedure: nb11.Procedure) -> dict[int | None, str]:
    return {None: "function", procedure.record_offset: "function",
            **{scope.record_offset: f"S{i}" for i, scope in enumerate(procedure.lexical_scopes)}}


def function_payload(corpus, row, symbols, data, types, *, assembly=False) -> dict:
    off = int(row["offset"], 0)
    proc = symbols.procedures[off]
    view = dc_asm.build_view(row, symbols, data)
    dossier = dreamcast.build_dossier(corpus, row, dump=symbols, data=data,
                                      asm_view=view, type_table=types)
    shape = dossier.shape
    scopes = _scope_ids(proc)
    variables = [dict(asdict(v), declaration=types.declaration(v.type_index, v.name),
                      scope_id=scopes.get(v.scope, f"record:{v.scope}"),
                      role={"this": "implicit this", "__$ReturnUdt": "ABI return storage"}.get(v.name, v.kind))
                 for v in proc.variables]
    inline = dreamcast._inline_clue_rows(corpus, row, symbols.source_lines.get(row["module"], ()))
    inline = dreamcast._inline_clue_groups(dreamcast._enrich_inline_clues(inline, dossier))
    for group in inline:
        group["containing_scopes"] = [scopes[scope.record_offset] for scope in proc.lexical_scopes
                                       if scope.address <= group["address"]
                                       and group["end_address"] <= scope.address + scope.size]
        group["helper_candidates"] = [
            {"name": candidate["name"], "module": candidate["module"],
             "dc_offset": int(candidate["offset"], 0),
             "signature": types.function(symbols.procedures[int(candidate["offset"], 0)].type_index,
                                          candidate["name"])}
            for name in group["definitions"] for candidate in corpus.by_name.get(name, ())
            if dreamcast._source_key(candidate["file"]) == dreamcast._source_key(group["source"])
            and int(candidate["line"], 0) == group["definition_line"]]
    local_symbols = [entry for entry in symbols.module_info.get(row["module"], ())
                     if entry.get("procedure") == proc.record_offset]
    events = dc_asm.control_events(view, data)
    for event in events.values():
        target = event.get("call_target_va")
        if target is not None:
            event["target_name"] = symbols.names.get(target)
            callee = symbols.procedures.get(target - dc_lines.POOL_BASE)
            if callee:
                event["target_name"] = callee.name
                event["target_signature"] = types.function(callee.type_index, callee.name)
    blocks = []
    for i, block in enumerate(view["blocks"]):
        item = {key: value for key, value in block.items() if key != "instructions"}
        item["id"] = f"B{i}"
        item["control_sites"] = [dict(event, address=address)
                                 for address, event in sorted(events.items())
                                 if block["start"] <= address < block["end"]]
        if assembly:
            item["instructions"] = block["instructions"]
        blocks.append(item)
    return {
        "signature": dossier.signatures[0], "type_index": proc.type_index,
        "procedure_record": proc.record_offset, "procedure_flags": proc.flags,
        "has_endarg_record": proc.endarg, "debug_shape": shape.to_dict(),
        "variables": variables, "local_symbols": local_symbols,
        "scopes": [dict(asdict(scope), id=scopes[scope.record_offset],
                        parent_id=scopes.get(scope.parent, f"record:{scope.parent}"))
                   for scope in proc.lexical_scopes],
        "inline_evidence": inline, "cfg": blocks,
    }


def _binding(entry: dict, types: Types) -> str:
    kind = entry["kind"]
    name = _text(entry.get("name", ""))
    declaration = types.declaration(entry["type_index"], name)
    if kind == "typedef":
        return f"typedef {declaration};"
    if kind == "constant":
        return f"{declaration} = {entry['value']};"
    return f"{declaration}; // {kind}, section {entry['segment']} +0x{entry['offset']:x}"


def render_function(payload: dict, types: Types) -> str:
    shape = payload["debug_shape"]
    fn = shape["function"]
    address = fn["address"]
    end = address + fn["emitted_size"]
    source = fn["source"]
    rows = [
        "// STATE[STUB]",
        f"// SOURCE: {_text(source['file'])}:{source['boundary_line']}",
        f"// FUNCTION: {_span(address, end)} ({fn['emitted_size']} SH4 bytes)",
        f"// TYPE: 0x{payload['type_index']:04x}; procedure record 0x{payload['procedure_record']:x}; "
        f"flags 0x{payload['procedure_flags']:02x}; linkage {fn['linkage']}",
        f"// DEBUG BODY: +0x{fn['debug_body']['start_offset']:x}..+0x{fn['debug_body']['end_offset']:x}",
        _text(payload["signature"]), "{",
    ]
    for title, kind in (("PARAMETERS", "param"), ("LOCALS", "local")):
        variables = [v for v in payload["variables"] if v["kind"] == kind]
        rows.append(f"    // {title} ({len(variables)} recorded)")
        for var in variables:
            rows.append(f"    // {_text(var['declaration'])}; // {var['storage']}; "
                        f"scope {var['scope_id']}; type 0x{var['type_index']:04x}"
                        + (f"; {var['role']}" if var.get("role", kind) != kind else ""))
        rows.append("    // ******")
    if not payload["has_endarg_record"]:
        rows.append("    // No S_ENDARG record: parameter/local boundary is not recorded.")
    if payload["local_symbols"]:
        rows.append("    // LOCAL TYPEDEFS / CONSTANTS / STATIC DATA")
        for entry in payload["local_symbols"]:
            rows.append("    // " + _binding(entry, types) + f" // scope record {entry.get('scope')}")

    if payload["scopes"]:
        rows.append("    // LEXICAL SCOPE TREE (recorded parent links; ranges are end-exclusive)")
        children = defaultdict(list)
        for scope in payload["scopes"]:
            children[scope["parent_id"]].append(scope)

        def scope_tree(parent, depth, seen):
            for scope in children[parent]:
                if scope["id"] in seen:
                    rows.append("    // invalid cyclic scope parent: " + scope["id"])
                    continue
                pad = "  " * depth
                rows.append(f"    // {pad}{scope['id']} {{ // "
                            f"{_span(scope['address'], scope['address'] + scope['size'])}; "
                            f"record 0x{scope['record_offset']:x}; parent {scope['parent_id']}"
                            + ("; name " + _text(scope["name"]) if scope["name"] else ""))
                for var in payload["variables"]:
                    if var["scope_id"] == scope["id"]:
                        rows.append(f"    // {pad}  {_text(var['declaration'])}; // {var['storage']}")
                scope_tree(scope["id"], depth + 1, seen | {scope["id"]})
                rows.append(f"    // {pad}}} // {scope['id']}")
        scope_tree("function", 0, set())
        for parent in children:
            if parent.startswith("record:"):
                rows.append("    // unresolved scope parent " + parent)
                scope_tree(parent, 0, set())

    line_map = shape["line_map"]
    if line_map:
        if not line_map["procedure_line_reliable"]:
            rows.append("    // Boundary line may belong to the preceding procedure; no leading-gap inference.")
        if line_map["bodyless"]:
            rows.append("    // Minimal 4-byte SH4 body; no body-line inference.")
        if line_map["gaps"]:
            rows.append("    // SOURCE GAPS (absent line rows, not evidence of a particular statement)")
            for gap in line_map["gaps"]:
                rows.append(f"    // {'LEADING ' if gap['leading'] else ''}GAP: "
                            f"{gap['first_missing_line']}..{gap['last_missing_line']} "
                            f"({gap['missing_lines']} lines in {_text(source['file'])})")

    if payload["inline_evidence"]:
        rows.append("    // INLINE EVIDENCE (source attribution; helper identity is a candidate)")
        for i, group in enumerate(payload["inline_evidence"]):
            rows.append(f"    // I{i}: {group['confidence']} {group['kind']}; "
                        f"{_span(group['address'], group['end_address'])}")
            rows.append(f"    //     {_text(group['source'])}; lines "
                        + ", ".join(str(line) for line in group["source_lines"]))
            if group.get("containing_scopes"):
                rows.append("    //     containing lexical scopes: " + ", ".join(group["containing_scopes"]))
            for helper in group["helper_candidates"]:
                rows.append(f"    //     helper candidate dc:0x{helper['dc_offset']:08x}: "
                            + _text(helper["signature"]))
            if not group["helper_candidates"]:
                rows.append("    //     helper definition unresolved")

    statements = shape["statements"]
    rows.append(f"    // FUNCTION BODY[dc:0x{address:08x}]: {len(statements)} line/address rows")
    events = defaultdict(list)
    for scope in payload["scopes"]:
        start = scope["address"]
        events[start].append((1, scope["record_offset"], f"BEGIN {scope['id']} (parent {scope['parent_id']})"))
        events[start + scope["size"]].append((1 if scope["size"] == 0 else 0,
                                             scope["end_record"], f"END {scope['id']}"))
    by_address = defaultdict(list)
    for statement in statements:
        by_address[statement["address"]].append(statement)
    for at in sorted(set(events) | set(by_address)):
        for _order, _record, event in sorted(events[at]):
            rows.append(f"    // <dc:0x{at:08x}> SCOPE {event}")
        for statement in by_address[at]:
            loc = statement["source"]
            rows.append(f"    // <dc:0x{at:08x}>|0x{at - address:03x}|+0x{statement['emitted_size']:03x}:"
                        f"'{loc['line']}' // {_text(loc['file'])}")
            for i, group in enumerate(payload["inline_evidence"]):
                if any(s["address"] == at and s["line"] == loc["line"]
                       and s["source"] == loc["file"] for s in group["statements"]):
                    rows.append(f"    //     INLINE I{i}")
            for call in statement["calls"]:
                target = call["name"] or (f"VA 0x{call['target_address']:x}"
                                         if call["target_address"] is not None else "<indirect>")
                rows.append(f"    //     CALL +0x{call['site_address'] - address:x}: "
                            f"{_text(target)} [{call['classification'] or 'unresolved'}]")
            if statement["branch_count"]:
                rows.append(f"    //     conditional branches: {statement['branch_count']}")
    rows.append("    // ******")

    rows.append("    // CONTROL FLOW (inferred SH4 basic blocks; separate from lexical scopes)")
    labels = {block["start"]: block["id"] for block in payload["cfg"]}
    for block in payload["cfg"]:
        pred = ", ".join(labels.get(a, f"dc:0x{a:x}") for a in block["predecessors"]) or "-"
        succ = ", ".join(labels.get(a, f"dc:0x{a:x}") for a in block["successors"]) or "-"
        rows.append(f"    // {block['id']}: {_span(block['start'], block['end'])}; "
                    f"pred {pred}; succ {succ}")
        for event in block["control_sites"]:
            rows.append(f"    //     +0x{event['address'] - address:x}: "
                        + ", ".join(f"{key}={hex(value) if key.endswith('_va') and value is not None else _text(value)}"
                                    for key, value in event.items() if key != "address"))
        for ins in block.get("instructions", []):
            rows.append(f"    //     +0x{ins['address'] - address:x}  {ins['mnemonic']} {ins['operands']}")
    rows.extend(["}", ""])
    return "\n".join(rows)


def render_types(types: Types) -> str:
    lines = [BANNER, "// All named NB11 type variants; sizes and offsets describe the Dreamcast build.", ""]
    for index in sorted(types.records):
        item = types.get(index)
        if item["kind"] not in ("class", "struct", "union", "enum"):
            continue
        name = _text(item["name"])
        lines.append(f"// TYPE 0x{index:04x}; size {types.size(index)}; properties 0x{item['flags']:04x}")
        if item.get("name_truncated"):
            lines.append(f"// Truncated LF_CLASS name {_text(item['recorded_name_prefix'])!r}; "
                         f"name source: {item['name_source']}.")
        if item["forward"]:
            lines.extend([f"{item['kind']} {name}; // forward reference", ""])
            continue
        lines.extend([f"{item['kind']} {name}", "{"])
        for entry in types.fields(item["fields"]):
            kind = entry["kind"]
            field_name = _text(entry.get("name", ""))
            if kind == "enumerator":
                lines.append(f"    {field_name} = {entry['value']},")
                continue
            if kind == "method":
                decl = types.function(entry["type"], field_name)
            else:
                decl = types.declaration(entry["type"], field_name) if "type" in entry else "unresolved"
            detail = "; ".join(f"{key}={value}" for key, value in entry.items()
                               if key not in ("name", "type", "leaf", "record_offset"))
            lines.append(f"    // {_text(decl)}; // {detail}")
        if item.get("vshape"):
            lines.append(f"    // VTABLE SHAPE type 0x{item['vshape']:04x}: "
                         + str(types.get(item["vshape"]).get("slots", [])))
        lines.extend(["};", ""])
    return "\n".join(lines)


def _stem(module: str) -> str:
    stem = re.sub(r"[^a-zA-Z0-9_.-]", "_", module.rsplit(".", 1)[0])
    return stem if stem and stem not in (".", "..") else "module"


def _read_manifest(output: Path) -> list[str]:
    manifest = output / "index.json"
    if output.exists() and any(output.iterdir()) and not manifest.is_file():
        raise dreamcast.DreamcastError(f"{output}: nonempty directory is not a structure export; choose --output")
    if not manifest.exists():
        return []
    try:
        previous = json.loads(manifest.read_text())
        if previous["schema"] != SCHEMA or previous["generator"] != GENERATOR:
            raise ValueError("unrecognized generator")
        files = previous["files"]
        if not isinstance(files, list) or any(not isinstance(name, str) or
            Path(name).is_absolute() or ".." in Path(name).parts for name in files):
            raise ValueError("invalid generated file paths")
        return files
    except (KeyError, ValueError, TypeError) as exc:
        raise dreamcast.DreamcastError(f"{manifest}: invalid export manifest: {exc}") from exc


def export(corpus, *, modules=None, output=DEFAULT_OUTPUT, assembly=False) -> dict:
    output = Path(output)
    if output.is_symlink() or (output.exists() and not output.is_dir()):
        raise dreamcast.DreamcastError(f"{output}: expected an ordinary output directory")
    previous = _read_manifest(output)
    selected = sorted({name if name.endswith(".obj") else name + ".obj"
                       for name in (modules or [row["module"] for row in corpus.functions])})
    by_module = {module: corpus.find("", module) for module in selected}
    unknown = [module for module, rows in by_module.items() if not rows]
    if unknown:
        raise dreamcast.NoMatch("unknown module(s): " + ", ".join(unknown))
    data = inputs.read_dreamcast_exe()
    symbols = nb11.parse(data)
    types = Types.from_symbols(symbols)
    summary = Counter()
    index = {"schema": SCHEMA, "generator": GENERATOR,
             "input": {"name": "H3.EXE", "sha256": inputs.DREAMCAST.sha256,
                       "size": inputs.DREAMCAST.size},
             "address_space": "Dreamcast .text offset", "assembly": assembly,
             "modules": [], "files": []}
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".dreamcast-structure-", dir=output.parent) as temp:
        stage = Path(temp)

        def write(name, content):
            path = stage / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            index["files"].append(name)

        def write_json(name, payload):
            write(name, json.dumps(payload, ensure_ascii=False, indent=2) + "\n")

        used = set()
        for module, rows in by_module.items():
            stem = _stem(module)
            if stem.lower() in used:
                raise dreamcast.DreamcastError(f"output filename collision for module {module}")
            used.add(stem.lower())
            payloads = [function_payload(corpus, row, symbols, data, types, assembly=assembly) for row in rows]
            info = symbols.module_info.get(module, [])
            lines = [BANNER, f"// COMPILAND: {module}", ""]
            for compiler in (entry for entry in info if entry["kind"] == "compiler"):
                lines.append(f"// COMPILER: {_text(compiler['version'])}; machine 0x{compiler['machine']:x}; "
                             f"flags 0x{compiler['flags']:x}")
            bindings = [entry for entry in info if entry["kind"] != "compiler" and entry.get("procedure") is None]
            if bindings:
                lines.extend(["", "// MODULE TYPEDEFS / CONSTANTS / DATA"])
                lines.extend("// " + _binding(entry, types) for entry in bindings)
            lines.append("")
            lines.extend(render_function(payload, types) for payload in payloads)
            cpp, js = f"sources/{stem}.cpp", f"sources/{stem}.json"
            write(cpp, "\n".join(lines))
            write_json(js, {"schema": SCHEMA, "module": module, "symbols": info, "functions": payloads})
            counts = {
                "functions": len(payloads),
                "locals": sum(v["kind"] == "local" for p in payloads for v in p["variables"]),
                "scopes": sum(len(p["scopes"]) for p in payloads),
                "inline_functions": sum(bool(p["inline_evidence"]) for p in payloads),
            }
            summary.update(counts)
            index["modules"].append(dict(module=module, cpp=cpp, json=js, **counts))
        write("types.h", render_types(types))
        write_json("types.json", {"schema": SCHEMA, "types": {
            f"0x{i:04x}": types.get(i) for i in sorted(types.records)},
            "aliases": {f"0x{i:04x}": sorted(names) for i, names in sorted(types.aliases.items())}})
        write_json("symbols.json", {"schema": SCHEMA, "modules": symbols.module_info})
        index["summary"] = dict(summary, types=len(types.records), modules=len(by_module))
        readme = [
            "# Dreamcast source structure", "", "Generated by `homm3 dreamcast structure`.", "",
            "Input: the pinned `H3.EXE` NB11 stream, SHA-256 `" + inputs.DREAMCAST.sha256 + "`.", "",
            "These C++ files are browsing stubs, not compilable reconstructions. All `dc:` coordinates",
            "are Dreamcast `.text` offsets; ranges are end-exclusive. JSON preserves record IDs,",
            "types, parent links, storage, source rows, control flow and inline evidence.", "",
            "`S_BLOCK32` parent links define lexical nesting, including coincident and zero-length scopes.",
            "A variable's lexical scope is recorded ownership, not a precise optimized live range.",
            "Implicit `this` and hidden return storage stay in the debug inventory, outside source signatures.",
            "Procedures without a function type record retain known arguments and mark the return type unavailable.",
            "Line spans can include frame code or literal pools. Gaps identify absent line-program rows;",
            "they cannot distinguish comments, braces, declarations, assertions or folded code.", "",
            "Inline groups are positive/probable source-attribution evidence, not explicit inline-site",
            "records. Helper identities are source-location candidates. No clue proves absence of inlining,",
            "and an emitted standalone helper may also be expanded elsewhere. No `inline` keyword is invented.", "",
            "`types.h` / `types.json` include every named class/struct/union/enum variant, field, base,",
            "method, virtual slot and underlying type record. Three truncated class names are recovered",
            "from independent `S_UDT` records and labelled. `symbols.json` retains module data, typedefs,",
            "constants and compiler metadata across the image. Unknown facts retain their type/record IDs.", "",
            "Regenerate all modules with `homm3 dreamcast structure`, or select modules with",
            "`homm3 dreamcast structure --module cursor --output /tmp/dc-cursor`.",
            "`--asm` adds decoded SH4 instructions to the C++ and JSON. Re-exporting replaces the",
            "previous selection in that output directory. Global types/symbols are always included.", "",
            "| Compiland | Functions | Locals | Scopes | Functions with inline clues | JSON |",
            "|---|---:|---:|---:|---:|---|",
        ]
        for module in index["modules"]:
            readme.append(f"| [{module['module']}]({module['cpp']}) | {module['functions']} | "
                          f"{module['locals']} | {module['scopes']} | {module['inline_functions']} | "
                          f"[records]({module['json']}) |")
        write("README.md", "\n".join(readme) + "\n")
        index["files"].append("index.json")
        (stage / "index.json").write_text(json.dumps(index, indent=2) + "\n", encoding="utf-8")
        # Finish extraction before publishing. Replace only this generator's files;
        # a filtered rerun removes its previous selection and leaves unrelated files alone.
        for name in set(previous) | set(index["files"]):
            path = output / name
            if any(p.is_symlink() for p in (path, *path.parents)):
                raise dreamcast.DreamcastError(f"refusing to write through a symlink: {path}")
        output.mkdir(exist_ok=True)
        for name in index["files"]:
            path = output / name
            path.parent.mkdir(parents=True, exist_ok=True)
            (stage / name).replace(path)
        for name in set(previous) - set(index["files"]):
            (output / name).unlink(missing_ok=True)
    return index
