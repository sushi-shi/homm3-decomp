BASELINE_HEADER = """\
# GENERATED by `homm3 build` / `homm3 status update`. DO NOT HAND-EDIT.
# Invariant: cur_fuzzy <= max_fuzzy <= hist_fuzzy.
# cur_fuzzy = current build; max_fuzzy = best score reached by this function's
# current source implementation; hist_fuzzy = all-time high across current and
# older implementations or scoring policies. A proven src_hash change resets MAX
# while hist_fuzzy retains the old peak. Unrelated CUR movement leaves MAX held.
# Migration note: the pre-split MAX was copied into HIST and MAX was seeded
# from that migration checkpoint's CUR; subsequent rows follow the rules above.
# Scores are observational:
# evidence/source gates, not a local percentage maximum, decide build validity.
# Retail RVA carries MAX/HIST across source-label promotion and same-body renames.
# src_hash fingerprints the function's own C++ tokens, excluding comments and
# formatting. Legacy text hashes migrate only on verified unchanged text. It lets
# `status check` distinguish an edit to that function from collateral codegen
# movement caused by another function, a header, or the delink generation.
# unit<TAB>fn<TAB>cur_fuzzy<TAB>max_fuzzy<TAB>hist_fuzzy<TAB>rva<TAB>src_hash
"""


@dataclass(frozen=True)
class MatchRow:
    cur: float | None
    max: float
    hist: float
    rva: int | None = None
    src_hash: str | None = None

    def __post_init__(self) -> None:
        """Reject a ledger state that confuses current, implementation, history."""
        if self.cur is not None and self.cur > self.max + 1e-9:
            raise ValueError(
                f"invalid match row: CUR {self.cur} exceeds MAX {self.max}")
        if self.max > self.hist + 1e-9:
            raise ValueError(
                f"invalid match row: MAX {self.max} exceeds HIST {self.hist}")

    @property
    def best(self) -> float:
        """Best score banked for the current source implementation (MAX)."""
        return self.max


def comparison_problems_by_unit(context=None) -> dict[str | None, list[str]]:
    """Comparison-input problems keyed by objdiff unit (None: not per unit)."""
    from homm3.build.normalized_freshness import freshness_problems, ValidationContext
    config = OBJDIFF_DIR / "objdiff.json"
    if not config.is_file():
        return {None: ["comparison configuration missing"]}
    seen = set()
    context = context or ValidationContext()
    normalized_root = context.resolve(OBJDIFF_DIR / "normalized")
    problems = {}
    for unit in json.loads(config.read_text()).get("units", []):
        found = []
        for side in ("base_path", "target_path"):
            path = context.resolve(OBJDIFF_DIR / unit[side])
            if not path.is_file():
                found.append(f"{path} is missing")
            elif normalized_root not in path.parents:
                found.append(f"{path} is not a normalized comparison object")
            else:
                found.extend(freshness_problems(path, seen, context=context))
        if found:
            problems.setdefault(unit.get("name"), []).extend(found)
    return problems


def comparison_problems(context=None) -> list[str]:
    """Every comparison input's problems, including the raw-object stamp chain."""
    return [problem for found in comparison_problems_by_unit(context).values()
            for problem in found]


# Above this many stale units a unit list stops being useful advice.
_LISTED_UNITS = 12


def fast_build_advice(units) -> str:
    """The targeted rebuild that refreshes these units' comparisons."""
    units = sorted(u for u in units if u)
    if units and len(units) <= _LISTED_UNITS:
        return f"`homm3 build --fast {' '.join(units)}`"
    return "`homm3 build --fast`"


def require_fresh_comparisons(context=None) -> None:
    """Validate every comparison input, including the raw-object stamp chain."""
    by_unit = comparison_problems_by_unit(context)
    if by_unit:
        problems = [problem for found in by_unit.values() for problem in found]
        common.die(f"stale normalized comparison objects; run "
                   f"{fast_build_advice(by_unit)}:\n  "
                   + "\n  ".join(problems[:10]))


# NINJA_STATUS is emitted for each scheduled edge, including in dry-run
# mode. Use our own marker, not Ninja's human/translated no-work message.
_PENDING = "[homm3 pending build edge] "


def pending_build_edges(units: set[str] | None = None) -> tuple[int, str]:
    """Ninja's dry run of the candidate objects: (status, combined output).

    Ask Ninja about its real command/dependency graph without building
    anything. Normalized stamps alone cannot detect a source edit before
    recompilation.
    """
    targets = sorted(units) if units else ["objects"]
    try:
        result = subprocess.run(["ninja", "-n", *targets], cwd=common.HOMM3_DIR,
                                env=dict(os.environ, NINJA_STATUS=_PENDING),
                                capture_output=True, text=True)
    except FileNotFoundError:
        common.die("ninja not found on PATH; run inside `nix develop .#build` "
                   "(or through the `homm3` wrapper)")
    return result.returncode, result.stdout + result.stderr


def pending_units(output: str) -> tuple[set[str], list[str]]:
    """(units with a pending compile, other pending edge descriptions)."""
    units, other = set(), []
    for line in output.splitlines():
        if not line.startswith(_PENDING):
            continue
        description = line[len(_PENDING):].strip()
        if description.startswith("VC6 "):
            units.add(description[4:].strip())
        else:
            other.append(description)
    return units, other


def require_built_sources(units: set[str] | None = None) -> None:
    """Never bank old object scores under the edited source's new hash."""
    returncode, output = pending_build_edges(units)
    if returncode or _PENDING in output:
        pending, _other = pending_units(output)
        common.die("candidate sources are not built; run "
                   f"{fast_build_advice(pending)} before checking or "
                   "updating current scores:\n" + output[-3000:])


COMPLETE_BUILD = "`homm3 build --fast` (all units)"


def require_complete_build(context=None) -> None:
    """`status update` banks every unit from one complete, fresh report.

    A shared-header edit moves CUR in many units, so a checkpoint of only
    some units would mix measurements of different source trees.
    """
    returncode, output = pending_build_edges()
    detail, stale = "", set()
    if returncode or _PENDING in output:
        stale, _other = pending_units(output)
        detail = output[-3000:]
    else:
        by_unit = comparison_problems_by_unit(context)
        if by_unit:
            stale = {unit for unit in by_unit if unit}
            detail = "\n  ".join([problem for found in by_unit.values()
                                  for problem in found][:10])
    if not detail:
        return
    names = sorted(stale)
    shown = ", ".join(names[:_LISTED_UNITS]) + (
        f" and {len(names) - _LISTED_UNITS} more" if len(names) > _LISTED_UNITS else "")
    which = f"{len(names)} unit(s) are stale ({shown})" if names else "the build is stale"
    common.die(f"status update banks every unit from one complete, fresh report; "
               f"{which}. Run {COMPLETE_BUILD} first:\n  {detail}")


UNBUILT = "unbuilt changes"
STALE_COMPARISON = "stale comparison objects"


@dataclass
class ReportView:
    """The scores a read-only view shows, and which units they lag behind."""
    report: dict
    stale: dict[str, str]
    note: str | None = None


def read_report_view() -> ReportView:
    """Fresh scores when every unit is built; else the last measured report.

    Read-only views never refuse because a unit has unbuilt edits: they show
    the last measurement and name the units whose rows lag their source.
    """
    from homm3.build.normalized_freshness import ValidationContext
    stale, note = {}, None
    returncode, output = pending_build_edges()
    if returncode:
        note = "Ninja could not check build freshness:\n" + output[-1500:]
    units, other = pending_units(output)
    for unit in units:
        stale[unit] = UNBUILT
    if other:
        note = (note + "\n" if note else "") + "other pending build edges: " + \
            ", ".join(sorted(set(other))[:8])
    context = ValidationContext()
    problems = comparison_problems_by_unit(context)
    for unit in problems:
        if unit is not None:
            stale.setdefault(unit, STALE_COMPARISON)
    if not stale and not problems and not returncode:
        return ReportView(refresh_report(context), {}, note)
    if not REPORT.is_file():
        common.die("no measured report yet; run "
                   f"{fast_build_advice(stale) if stale else '`homm3 build`'}")
    if None in problems:
        note = (note + "\n" if note else "") + "; ".join(problems[None][:3])
    return ReportView(load_report(), stale, note)


def warn_stale(view: ReportView) -> None:
    """Name the lagging units on stderr so --json stdout stays parseable."""
    if not view.stale and not view.note:
        return
    import datetime
    when = datetime.datetime.fromtimestamp(REPORT.stat().st_mtime).strftime(
        "%Y-%m-%d %H:%M") if REPORT.is_file() else "unknown time"
    out = sys.stderr
    print(f"[status] WARNING: showing the last measured report "
          f"({REPORT.relative_to(common.HOMM3_DIR)}, {when}).", file=out)
    if view.stale:
        for reason in sorted(set(view.stale.values())):
            names = sorted(u for u, why in view.stale.items() if why == reason)
            shown = ", ".join(names[:_LISTED_UNITS])
            more = (f" and {len(names) - _LISTED_UNITS} more"
                    if len(names) > _LISTED_UNITS else "")
            print(f"[status]   {len(names)} unit(s) with {reason}: {shown}{more}.",
                  file=out)
        print(f"[status]   Their rows (marked *) are stale; refresh them with "
              f"{fast_build_advice(view.stale)}.", file=out)
    if view.note:
        print(f"[status]   {view.note}", file=out)


def load_report(path: Path | None = None) -> dict:
    """Read a previously produced report; never build or run objdiff."""
    return json.loads((path or REPORT).read_text())


def refresh_report(context=None) -> dict:
    """Validate comparison inputs, produce a report, then read its result.

    `context` may carry content hashes read since the last comparison write.
    """
    from homm3.build.report import generate
    require_fresh_comparisons(context)
    return load_report(generate(OBJDIFF_DIR))


def fn_fuzzy(report: dict) -> dict:
    """(unit, fn) -> fuzzy_match_percent, for every function in the report."""
    return {
        (unit.get("name", "?"), fn.get("name", "?")):
            float(fn.get("fuzzy_match_percent") or 0.0)
        for unit in report.get("units", [])
        for fn in (unit.get("functions", []) or [])
    }


def _definition_text(raw: str, masked: str, after: int) -> str | None:
    """Return the definition following one VA annotation, if it has a body.

    `masked` has comments and literals blanked without changing offsets, so
    braces inside either cannot terminate the extent. VC6-era source has no
    lambdas or braced default arguments: the first top-level brace before a
    semicolon is the function body.
    """
    n = len(masked)
    start = after
    while start < n and masked[start].isspace():
        start += 1
    parens = brackets = 0
    opening = None
    i = start
    while i < n:
        char = masked[i]
        if char == "(":
            parens += 1
        elif char == ")":
            parens = max(0, parens - 1)
        elif char == "[":
            brackets += 1
        elif char == "]":
            brackets = max(0, brackets - 1)
        elif char == "{" and parens == 0 and brackets == 0:
            opening = i
            break
        elif char == ";" and parens == 0 and brackets == 0:
            return None
        i += 1
    if opening is None:
        return None

    depth = 1
    i = opening + 1
    while i < n and depth:
        if masked[i] == "{":
            depth += 1
        elif masked[i] == "}":
            depth -= 1
        i += 1
    return raw[start:i] if depth == 0 else None


_MAC_ADDRESS_TAIL = re.compile(r"\s*(?:DC_ADDRESS|MAC_(?:COMPGEN_)?ADDRESS)\s*\([^()]*\)")


def _after_windows_claim(masked: str, end: int) -> int:
    """Offset after a VA claim and the Mac address written on its line.

    The Mac address is a second target's location, not part of the function's
    implementation, so adding or correcting it must not reset MAX.
    """
    after = end + 1
    while match := _MAC_ADDRESS_TAIL.match(masked, after):
        after = match.end()
    return after


def _parameter_arity(parameters: str) -> int | None:
    """Count simple declaration parameters, refusing ambiguous expressions."""
    parameters = parameters.strip()
    if parameters in ("", "void"):
        return 0
    # Defaults and expressions can use angle brackets as operators. Leave
    # those signatures unresolved rather than guessing their ownership.
    if any(token in parameters for token in ("=", "...", "{", "}")):
        return None
    stack: list[str] = []
    closers = {"(": ")", "[": "]", "<": ">"}
    count = 1
    for char in parameters:
        if char in closers:
            stack.append(closers[char])
        elif char in ")]>":
            if not stack or stack.pop() != char:
                return None
        elif char == "," and not stack:
            count += 1
    return None if stack else count


def _canonical_definition_text(raw: str, masked: str, after: int,
                               fn: str) -> str | None:
    """Resolve an annotated definition or its RVA-ordered redeclaration.

    Inline bodies sometimes must remain in Dreamcast source order while an
    annotated redeclaration records the retained COMDAT's later retail order.
    Hash the unique active body in both arrangements so moving only the VA
    annotation cannot masquerade as an edit to the function itself.
    """
    direct = _definition_text(raw, masked, after)
    if direct is not None:
        return direct

    from homm3.vc6 import _source

    definitions = _source.find_definitions(raw, fn)
    if len(definitions) > 1:
        # A separately annotated overload still owns its body when the
        # declaration's arity identifies exactly one active definition.
        # Same-arity overloads remain unknown; this is not a type resolver.
        declaration_end = masked.find(";", after)
        arities: set[int] = set()
        if declaration_end >= 0:
            for name in {definition.name for definition in definitions}:
                pattern = re.compile(r"(?<![\w:])" + re.escape(name) + r"\s*\(")
                for match in pattern.finditer(masked, after, declaration_end):
                    opening = match.end() - 1
                    closing = _source._match_paren(masked, opening)
                    if closing is not None and closing < declaration_end:
                        arity = _parameter_arity(masked[opening + 1:closing])
                        if arity is not None:
                            arities.add(arity)
        if len(arities) == 1:
            arity = next(iter(arities))
            candidates = [(_parameter_arity(masked[definition.par_open + 1:
                                                  definition.par_close]), definition)
                          for definition in definitions]
            if all(count is not None for count, _ in candidates):
                definitions = [definition for count, definition in candidates
                               if count == arity]
    if len(definitions) != 1:
        return None
    definition = definitions[0]
    line_start = raw.rfind("\n", 0, definition.head) + 1
    return raw[line_start:definition.body_close + 1]


def _source_definitions(*, source_root: Path | None = None,
                        only_units: set[str] | None = None):
    """Yield each VA-owned function's own definition, keyed like objdiff.

    The source VA supplies stable retail identity, avoiding a lossy
    mangled-name-to-C++-name join. Functions without an attributable
    definition deliberately get no fingerprint: unknown must not be mistaken
    for an edit and turn collateral optimizer movement into a reported drop.
    """
    from homm3.build import configure
    from homm3.retail_labels import source

    root = source_root if source_root is not None else common.HOMM3_DIR
    by_identity: dict[tuple[str, int], list[tuple[str, str]]] = {}
    for key, rva in function_rvas().items():
        if only_units is None or key[0] in only_units:
            by_identity.setdefault((key[0], rva), []).append(key)

    _build, _profiles, units = configure.load_manifest()
    va_head, _arity, _prototype = source.MACRO_HEADS["VA"]
    for unit in units:
        unit_name = unit["unit"]
        if only_units is not None and unit_name not in only_units:
            continue
        path = root / unit["source"]
        raw = path.read_text(errors="replace")
        masked = source.mask_lexical_noise(raw)
        for _start, end, args, _raw_args in source.macro_invocations(
                masked, va_head, raw):
            if end is None or len(args) != 2 \
                    or not source.ADDR_ARG_RE.match(args[0]):
                continue  # source-claim gate owns malformed annotations
            rva = source.rva_of(args[0], str(path))
            keys = by_identity.get((unit_name, rva), ())
            if not keys:
                continue
            for key in keys:
                definition = _canonical_definition_text(
                    raw, masked, _after_windows_claim(masked, end), key[1])
                if definition is None:
                    continue
                yield key, definition
    # Canonical header bodies carry their own VA annotations. Their retail
    # comparison carrier may be any emitted TU; identity is the RVA, while
    # the fingerprint must follow the physical header definition.
    from homm3.retail_labels.headers import claim_files
    keys_by_rva = {}
    for (_unit, rva), keys in by_identity.items():
        keys_by_rva.setdefault(rva, []).extend(keys)
    for path in claim_files(root):
        raw = path.read_text(errors="replace")
        masked = source.mask_lexical_noise(raw)
        for _start, end, args, _raw_args in source.macro_invocations(masked, va_head, raw):
            if end is None or len(args) != 2 or not source.ADDR_ARG_RE.match(args[0]):
                continue
            rva = source.rva_of(args[0], str(path))
            for key in keys_by_rva.get(rva, ()):
                definition = _canonical_definition_text(
                    raw, masked, _after_windows_claim(masked, end), key[1])
                if definition is not None:
                    yield key, definition


def _legacy_hash(definition: str) -> str:
    import hashlib
    return hashlib.sha1(definition.encode("utf-8", "replace")).hexdigest()[:12]


def source_hashes(*, legacy: bool = False, source_root: Path | None = None,
                  only_units: set[str] | None = None) -> dict[tuple[str, str], str]:
    """Fingerprint live or isolated candidate definitions using admitted RVAs."""
    from homm3.core.cpp_tokens import fingerprint
    digest = _legacy_hash if legacy else fingerprint
    return {key: digest(definition) for key, definition in
            _source_definitions(source_root=source_root, only_units=only_units)}


def source_hash_pair(*, only_units: set[str] | None = None) -> tuple[dict, dict]:
    """Current and migration hashes from one source scan; never persisted."""
    from homm3.core.cpp_tokens import fingerprint
    current, legacy = {}, {}
    for key, definition in _source_definitions(only_units=only_units):
        current[key] = fingerprint(definition)
        legacy[key] = _legacy_hash(definition)
    return current, legacy


def migrate_source_hashes(rows: dict, hashes: dict, legacy: dict) -> dict:
    """Change fingerprint format only when the old text still matches exactly."""
    return {key: replace(row, src_hash=hashes[key])
            if (row.src_hash is not None and not row.src_hash.startswith("tokens1:")
                and row.src_hash == legacy.get(key) and key in hashes)
            else row for key, row in rows.items()}


def parse_baseline(contents: str) -> dict[tuple[str, str], MatchRow]:
    """Parse one ledger revision without depending on a worktree path."""
    rows = {}
    for line in contents.splitlines():
        if not line or line.startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) == 3:  # legacy unit/fn/max; update rewrites it
            unit, fn, value = cols
            score = float(value)
            rows[(unit, fn)] = MatchRow(score, score, score)
        elif len(cols) in (6, 7):
            if len(cols) == 7:
                unit, fn, cur, maximum, historical, rva, raw_hash = cols
                src_hash = None if raw_hash == "-" else raw_hash
            else:
                unit, fn, cur, maximum, historical, rva = cols
                src_hash = None
            rows[(unit, fn)] = MatchRow(
                None if cur == "-" else float(cur),
                float(maximum), float(historical),
                None if rva == "-" else int(rva, 0), src_hash)
        else:
            common.die(f"malformed match baseline row: {line!r}")
    return rows


def load_baseline(path: Path | None = None) -> dict[tuple[str, str], MatchRow]:
    path = path or BASELINE
    return parse_baseline(path.read_text()) if path.is_file() else {}


def baseline_at_ref(ref: str) -> dict[tuple[str, str], MatchRow]:
    """Read a committed comparison point without changing the lane ledger."""
    relative = BASELINE.relative_to(common.HOMM3_DIR)
    result = subprocess.run(
        ["git", "show", f"{ref}:{relative}"], cwd=common.HOMM3_DIR,
        capture_output=True, text=True)
    if result.returncode:
        common.die(f"cannot read baseline at {ref!r}: {result.stderr.strip()}")
    return parse_baseline(result.stdout)


def baseline_history() -> str:
    """One read of immutable Git history; callers may share it within a build."""
    relative = BASELINE.relative_to(common.HOMM3_DIR)
    result = subprocess.run(
        ["git", "log", "-p", "--format=", "--", str(relative)],
        cwd=common.HOMM3_DIR, capture_output=True, text=True)
    return result.stdout if result.returncode == 0 else ''


def historical_maxima_from_git(patch: str | None = None) -> dict[object, float]:
    """Recover peaks from every tracked baseline revision during migration.

    `git log -p` exposes each value when it first enters the generated file,
    including maxima that legacy practice later lowered. This is deliberately
    read-only Git history: the status writer remains the sole TSV writer.
    """
    patch = baseline_history() if patch is None else patch
    maxima: dict[object, float] = {}
    for patch_line in patch.splitlines():
        if not patch_line.startswith("+") or patch_line.startswith("+++"):
            continue
        cols = patch_line[1:].split("\t")
        try:
            if len(cols) == 3:
                identity, value = (cols[0], cols[1]), float(cols[2])
            elif len(cols) in (6, 7):
                # New-format history belongs to the retail body, not the
                # source label. Keep the label fallback for rows without an
                # admitted RVA, but carry peaks through later renames by RVA.
                identity = ((cols[0], cols[1]) if cols[5] == "-"
                            else int(cols[5], 0))
                value = max(float(cols[2]) if cols[2] != "-" else 0.0,
                            float(cols[3]), float(cols[4]))
            else:
                continue
        except ValueError:
            continue
        maxima[identity] = max(maxima.get(identity, 0.0), value)
    return maxima


def seed_historical_maxima(rows: dict, maxima: dict) -> tuple[dict, int]:
    """Return rows with any recoverable pre-cur/max/hist peaks restored."""
    seeded, recovered = {}, 0
    for key, row in rows.items():
        historical = max(row.hist, maxima.get(key, 0.0),
                         maxima.get(row.rva, 0.0)
                         if row.rva is not None else 0.0)
        recovered += historical > row.hist + 1e-9
        seeded[key] = MatchRow(
            row.cur, row.max, historical, row.rva, row.src_hash)
    return seeded, recovered


def function_rvas() -> dict[tuple[str, str], int]:
    """Current report identity, keyed by (unit, function label)."""
    if not SYMBOL_NAMES.is_file():
        return {}
    data = "\n".join(line for line in SYMBOL_NAMES.read_text().splitlines()
                     if not line.startswith("#"))
    out = {}
    for row in csv.DictReader(io.StringIO(data)):
        if row.get("kind") == "func":
            out[(row["unit"], row["name"])] = int(row["rva"], 0)
    return out


def load_baseline_comments() -> tuple:
    """Legacy rationale comments, anchored to the row they precede.

    Old revisions documented deliberate manual max-lowering in comments. The
    generated cur/max/hist format supersedes that practice, but automatic
    rewrites retain those historical explanations. The leading generated or
    legacy header block is excluded. Returns (anchored, trailing).
    """
    anchored, pending = {}, []
    if not BASELINE.is_file():
        return anchored, []
    seen_row = False
    for line in BASELINE.read_text().splitlines():
        if line.startswith("#"):
            # The leading block is generated metadata, including legacy header
            # text. Only comments embedded among data rows are historical notes.
            if not seen_row:
                continue
            pending.append(line)
        elif line:
            seen_row = True
            unit, fn = line.split("\t", 2)[:2]
            if pending:
                anchored[(unit, fn)] = pending
                pending = []
    return anchored, pending


def write_baseline(rows: dict[tuple[str, str], MatchRow]) -> None:
    anchored, trailing = load_baseline_comments()
    out = []
    for key in sorted(rows):
        out.extend(anchored.pop(key, ()))
        row = rows[key]
        cur = "-" if row.cur is None else f"{row.cur:.4f}"
        rva = "-" if row.rva is None else f"0x{row.rva:x}"
        src_hash = row.src_hash or "-"
        out.append(f"{key[0]}\t{key[1]}\t{cur}\t{row.max:.4f}\t"
                   f"{row.hist:.4f}\t{rva}\t{src_hash}")
    # Comments whose row is gone (a promoted fn's flat-name row) outlive it:
    # dropping them is the very defect this function exists to prevent.
    for orphan in anchored.values():
        out.extend(orphan)
    out.extend(trailing)
    BASELINE.write_text(BASELINE_HEADER + f"# score_policy={SCORE_POLICY}\n" + "\n".join(out) + "\n")


def policy_baseline(rows: dict, contents: str | None = None) -> dict:
    """A new comparison policy resets implementation MAX, preserving HIST.

    Source hashes remain source hashes. A stricter relocation verdict cannot
    inherit a maximum measured while callee identities/addends were ignored.
    """
    if contents is None:
        contents = BASELINE.read_text() if BASELINE.is_file() else ''
    if f'# score_policy={SCORE_POLICY}' in contents.splitlines():
        return rows
    return {key: MatchRow(None, 0.0, row.hist, row.rva, row.src_hash)
            for key, row in rows.items()}


def projected_rows(report: dict, *, fingerprint_pair: tuple[dict, dict] | None = None) -> dict:
    """Read-only checkpoint projection for summaries, including fast builds."""
    hashes, legacy = fingerprint_pair if fingerprint_pair is not None else source_hash_pair()
    previous = migrate_source_hashes(policy_baseline(load_baseline()), hashes, legacy)
    rows, _stats = update_rows(fn_fuzzy(report), previous, function_rvas(), hashes)
    return rows


def max_measures(report: dict, rows: dict) -> tuple[int, int, float]:
    total = matched = size_total = 0
    weighted = 0.0
    for unit in report.get("units", []):
        for fn in unit.get("functions", []) or []:
            maximum = rows[(unit.get("name", "?"), fn.get("name", "?"))].max
            size = int(fn.get("size") or 0)
            total += 1
            matched += maximum == 100
            weighted += maximum * size
            size_total += size
    return total, matched, weighted / size_total if size_total else 0.0


def overall_line(report: dict, *, rows: dict | None = None,
                 fingerprint_pair: tuple[dict, dict] | None = None) -> str:
    if rows is None:
        rows = projected_rows(report, fingerprint_pair=fingerprint_pair)
    total, matched, fuzzy = max_measures(report, rows)
    units = len(report.get("units", []))
    pct = 100.0 * matched / total if total else 0.0
    return (f"MAX {matched}/{total} functions exact ({pct:.1f}%), "
            f"{fuzzy:.2f}% weighted MAX across {units} unit(s)")


def fast_max_movements(report: dict, units: set[str] | None,
                       fingerprint_pair: tuple[dict, dict]) -> None:
    """Print per-function MAX changes for the fast loop without banking them.

    A function's retail RVA carries its peak through a label rename. Its own
    source hash decides whether a lower current score resets MAX; unrelated
    TU/header codegen movement leaves MAX held and stays silent.
    """
    hashes, legacy = fingerprint_pair
    previous = migrate_source_hashes(load_baseline(), hashes, legacy)
    rvas = function_rvas()
    current = fn_fuzzy(report)
    projected, _stats = update_rows(current, previous, rvas, hashes)
    by_rva = {}
    for key, row in previous.items():
        if row.rva is not None:
            by_rva.setdefault(row.rva, []).append((key, row))

    changed_units = 0
    seen_units = set()
    for unit in sorted(report.get("units", []), key=lambda row: row.get("name", "")):
        name = unit.get("name", "?")
        if units is not None and name not in units:
            continue
        seen_units.add(name)
        keys = [(name, fn.get("name", "?"))
                for fn in unit.get("functions", []) or []]
        changes = []
        for key in keys:
            _old_key, old = _previous_row(key, rvas.get(key), previous, by_rva)
            new = projected[key]
            if old is None:
                changes.append((key[1], "NEW", None, new.max, ""))
                continue
            if new.max > old.max + EPS:
                changes.append((key[1], "UP", old.max, new.max, ""))
            elif new.max < old.max - EPS:
                held = old.cur is not None and abs(new.cur - old.cur) <= EPS
                kind = "RESET" if held else "CHANGED-CUR"
                note = (f"CUR held at {new.cur:.2f}%" if held else
                        f"banked CUR {old.cur:.2f}% -> {new.cur:.2f}%"
                        if old.cur is not None else "prior CUR unavailable")
                changes.append((key[1], kind, old.max, new.max, note))
        if not changes and units is None:
            continue
        exact = sum(projected[key].max >= 100.0 - 1e-6 for key in keys)
        print(f"[build] {name}: {exact}/{len(keys)} at MAX 100")
        if not changes:
            print("[build]   no MAX change")
            continue
        changed_units += 1
        for fn, kind, old_max, new_max, note in changes:
            before = "new" if old_max is None else f"{old_max:.2f}%"
            suffix = f"; {note}" if note else ""
            print(f"[build]   {before} -> {new_max:.2f}% MAX  {fn} [{kind}{suffix}]")
    for name in sorted((units or set()) - seen_units):
        print(f"[build] {name}: no paired functions in report")
    if units is None and not changed_units:
        print("[build] no per-function MAX change across this fast build")
    sys.stdout.flush()


def fresh_fingerprints(report: dict, stale) -> tuple[dict, dict] | None:
    """Source hashes for units whose objects reflect their source.

    A stale unit's scores predate its edit; hashing its new source would
    read as a MAX reset, so its hashes stay unknown and MAX is held.
    """
    if not stale:
        return None
    units = {unit.get("name") for unit in report.get("units", [])}
    return source_hash_pair(only_units=units - set(stale))


def cmd_summary(report: dict, stale=()) -> int:
    rows = projected_rows(report, fingerprint_pair=fresh_fingerprints(report, stale))
    print("  Objective: MAX (projected; ledger unchanged)")
    print("  Unit        Funcs (MAX 100%)   Weighted MAX")
    print("  " + "-" * 40)
    for unit in sorted(report.get("units", []),
                       key=lambda u: u.get("name", "")):
        total, matched, fuzzy = max_measures({"units": [unit]}, rows)
        name = unit.get("name", "?") + ("*" if unit.get("name") in stale else "")
        print(f"  {name:<12} {matched:>3}/{total:<3}"
              f"      {fuzzy:>7.2f}%")
    print("  " + "-" * 40)
    print(f"  Overall: {overall_line(report, rows=rows)}")
    print(f"  CUR diagnostics: {REPORT}")
    return 0


def _previous_row(key, rva, previous, by_rva):
    """Use the same retail identity for checkpoint updates and drop reports."""
    old_key, old = key, previous.get(key)
    candidates = by_rva.get(rva, []) if rva is not None else []
    if len(candidates) == 1:
        return candidates[0]
    if old is not None and rva is not None and old.rva not in (None, rva):
        old = None  # this label now claims a different retail body
    return old_key, old


def update_rows(current: dict, previous: dict, rvas: dict,
                hashes: dict | None = None) -> tuple[dict, dict]:
    """Pure CUR/MAX/HIST update; stable RVA, not label, owns history.

    CUR <= MAX <= HIST. MAX is monotone only while the function's own source
    hash is unchanged; a proven edit starts a new implementation and resets
    MAX to CUR. HIST never forgets a peak reached by an older implementation.
    Unknown hashes are conservative: without proof of an edit, MAX is held.
    """
    hashes = hashes or {}
    by_rva = {}
    for key, row in previous.items():
        if row.rva is not None:
            by_rva.setdefault(row.rva, []).append((key, row))

    rows, consumed = {}, set()
    stats = {"added": 0, "raised": 0, "reset": 0,
             "migrated": 0, "retired": 0}
    for key, raw_value in current.items():
        value = round(raw_value, 4)
        rva = rvas.get(key)
        old_key, old = _previous_row(key, rva, previous, by_rva)

        if old is None:
            rows[key] = MatchRow(
                value, value, value, rva, hashes.get(key))
            stats["added"] += 1
            continue
        consumed.add(old_key)
        if old_key != key:
            stats["migrated"] += 1
        current_hash = hashes.get(key)
        edited = (old.src_hash is not None and current_hash is not None
                  and current_hash != old.src_hash)
        maximum = value if edited else max(old.max, value)
        historical = max(old.hist, old.max, value)
        if edited and maximum < old.max - 1e-9:
            stats["reset"] += 1
        elif maximum > old.max + 1e-9:
            stats["raised"] += 1
        rows[key] = MatchRow(
            value, maximum, historical,
            rva if rva is not None else old.rva,
            current_hash if current_hash is not None else old.src_hash)

    represented_rvas = {row.rva for row in rows.values() if row.rva is not None}
    for key, old in previous.items():
        if key in consumed or key in rows:
            continue
        # The source map includes claims outside the current report. Only
        # an actual replacement row can retire an old label's history.
        if old.rva is not None and old.rva in represented_rvas:
            continue
        # Old flat labels had no RVA. A missing 0% row records no matching
        # achievement, so label promotion may retire it without losing history.
        if old.rva is None and old.hist <= 1e-9:
            stats["retired"] += 1
            continue
        rows[key] = MatchRow(
            None, old.max, old.hist, old.rva, old.src_hash)
    return rows, stats


def guard_peaks(previous: dict, rows: dict, *,
                allow_loss: bool = False) -> tuple[dict, list[str]]:
    """Keep every banked peak an update would lose; return (rows, losses).

    `update_rows` never lowers HIST, nor MAX under an unchanged source hash.
    A lower row therefore means the update lost the banked row's identity -
    a stale RVA map or label join - not a measurement. Unless `allow_loss`,
    such a row keeps its banked MAX (same source) and HIST.
    """
    kept, losses = dict(rows), []
    for key, old in previous.items():
        new = rows.get(key)
        if new is None:
            continue
        same_source = old.src_hash is not None and new.src_hash == old.src_hash
        lost_max = same_source and new.max < old.max - 1e-9
        lost_hist = new.hist < old.hist - 1e-9
        if not (lost_max or lost_hist):
            continue
        moved = (f"; RVA {old.rva:#x} -> {new.rva:#x}" if None not in (old.rva, new.rva)
                 and old.rva != new.rva else "")
        losses.append(f"{key[0]} {key[1]}: MAX {old.max:.2f} -> {new.max:.2f}, "
                      f"HIST {old.hist:.2f} -> {new.hist:.2f}"
                      + ("" if same_source else " (source edited)") + moved)
        if not allow_loss:
            maximum = max(new.max, old.max) if same_source else new.max
            kept[key] = MatchRow(new.cur, maximum, max(new.hist, old.hist, maximum),
                                 new.rva, new.src_hash)
    return kept, losses


def report_peak_losses(losses: list[str], *, allowed: bool) -> None:
    if not losses:
        return
    verb = "LOWERED (--allow-ledger-loss)" if allowed else "kept their banked peaks"
    print(f"[status] WARNING: {len(losses)} row(s) would lose a banked peak and {verb}; "
          "check build/gen freshness (run `homm3 delink`) before banking:", file=sys.stderr)
    for line in losses[:20]:
        print(f"[status]   {line}", file=sys.stderr)
    if len(losses) > 20:
        print(f"[status]   ... {len(losses) - 20} more", file=sys.stderr)


def cmd_update(report: dict, *, fingerprint_pair: tuple[dict, dict] | None = None,
               history_patch: str | None = None, allow_loss: bool = False) -> int:
    require_complete_build()
    banked = load_baseline()
    previous = policy_baseline(banked)
    if previous != banked:
        print("[status] scoring policy changed: MAX reseeded from CUR; HIST retained")
    previous, recovered = seed_historical_maxima(
        previous, historical_maxima_from_git(history_patch))
    hashes, legacy = fingerprint_pair if fingerprint_pair is not None else source_hash_pair()
    previous = migrate_source_hashes(previous, hashes, legacy)
    rows, stats = update_rows(
        fn_fuzzy(report), previous, function_rvas(), hashes)
    rows, losses = guard_peaks(previous, rows, allow_loss=allow_loss)
    report_peak_losses(losses, allowed=allow_loss)
    write_baseline(rows)
    print("[status] baseline: "
          f"{stats['added']} added, {stats['migrated']} migrated, "
          f"{stats['raised']} checkpoint(s) raised, "
          f"{stats['reset']} MAX reset(s) by source edit, "
          f"{recovered} historical peaks recovered, "
          f"{stats['retired']} empty legacy retired -> {BASELINE.name} "
          f"({len(rows)} rows)")
    return 0


def checkpoint_events(current: dict, hashes: dict,
                      rows: dict, rvas: dict | None = None) -> list[tuple]:
    """Source edits whose new implementation MAX is below the old MAX.

    An unchanged source hash leaves MAX banked, so unrelated CUR movement is
    never reported. A changed hash starts a new implementation; report it when
    that implementation resets MAX below the preceding implementation's MAX.
    The report is observational and HIST preserves the old peak.
    """
    rvas = rvas or {}
    by_rva = {}
    for key, row in rows.items():
        if row.rva is not None:
            by_rva.setdefault(row.rva, []).append((key, row))
    events = []
    for key in sorted(current.keys() | hashes.keys()):
        _old_key, row = _previous_row(key, rvas.get(key), rows, by_rva)
        if row is None:
            continue
        value = current.get(key)
        src_hash = hashes.get(key)
        if (row.src_hash is None or src_hash is None
                or src_hash == row.src_hash):
            continue
        if value is None:
            kind = "MISSING"
        elif value < row.max - EPS:
            kind = ("RESET" if row.cur is not None
                    and abs(value - row.cur) <= EPS else "CHANGED-CUR")
        else:
            continue
        events.append((kind, key, row.max, row.hist, row.cur, value))
    return events


def checkpoint_drops(current: dict, hashes: dict,
                     rows: dict, rvas: dict | None = None) -> list[tuple]:
    """Compatibility view of edited MAX drops for existing callers."""
    return [(key, maximum, hist, value)
            for _kind, key, maximum, hist, _previous_cur, value in
            checkpoint_events(current, hashes, rows, rvas)]


def cmd_check(report: dict, *, fingerprint_pair: tuple[dict, dict] | None = None,
              baseline_ref: str | None = None) -> int:
    require_built_sources()
    rows = baseline_at_ref(baseline_ref) if baseline_ref else load_baseline()
    if not rows:
        print("[status] no baseline yet - run `homm3 status update`")
        return 0
    current = fn_fuzzy(report)
    hashes, legacy = fingerprint_pair if fingerprint_pair is not None else source_hash_pair()
    rows = migrate_source_hashes(rows, hashes, legacy)
    events = checkpoint_events(current, hashes, rows, function_rvas())
    if baseline_ref:
        print(f"[status] comparing before banking against {baseline_ref}")
    for kind, (unit, fn), previous_max, historical, previous_cur, value in events:
        now = f"{value:.2f}%" if value is not None else "MISSING"
        prior = f"{previous_cur:.2f}%" if previous_cur is not None else "MISSING"
        print(f"[status] {kind} SOURCE-EDIT MAX DROP {unit} {fn}: "
              f"{previous_max:.2f}% -> {now} "
              f"(banked CUR {prior}; HIST held at {historical:.2f}%)")
    if events:
        counts = {kind: sum(event[0] == kind for event in events)
                  for kind in ("RESET", "CHANGED-CUR", "MISSING")}
        print(f"[status] {len(events)} changed function(s) reset MAX below "
              "the preceding implementation's MAX. This is observational; "
              "HIST remains banked and source/evidence gates decide validity. "
              f"RESET {counts['RESET']}, changed CUR {counts['CHANGED-CUR']}, "
              f"missing {counts['MISSING']}.")
        return 0
    print(f"[status] no source edit lowered MAX ({len(rows)} banked "
          "functions; unchanged-source CUR dips are never reported)")
    return 0


