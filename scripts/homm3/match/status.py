#!/usr/bin/env python3
"""homm3.match.status - the objdiff scoreboard and the match ratchet.

  homm3 status           per-unit table + overall (on-demand human view;
                         never printed by the build tail - gruntz doctrine)
  homm3 status functions [FILTER]
                         per-function current / max / historical scores
  homm3 status update [--accept-regressions]
                         refresh current scores and raise maxima/history;
                         an explicit accept may lower max, never history
  homm3 status check     print every function below its recorded best;
                         --gate exits 1 on any drop (the BUILD runs this -
                         deliberate divergence from both siblings, where the
                         baseline is observational: here a regression fails
                         `homm3 build`.)

Baseline: config/match_baseline.tsv, generated by this module. Stable retail
RVAs carry cur/max/hist across flat-name -> decorated-name promotion. Legacy
three-column rows are migrated automatically; a missing zero-score legacy row
is retired because it contains no historical match evidence. The report is
regenerated fresh each call (`objdiff-cli report generate`, sub-second at this
unit count; homm2's input-identity cache is future work).
"""
from __future__ import annotations

import csv
import io
import json
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

from homm3.core import common

OBJDIFF_DIR = common.HOMM3_DIR / "build/objdiff"
REPORT = OBJDIFF_DIR / "report.json"
BASELINE = common.HOMM3_DIR / "config/match_baseline.tsv"
SYMBOL_NAMES = common.HOMM3_DIR / "build/gen/symbol_names.csv"
EPS = 0.01

BASELINE_HEADER = """\
# GENERATED by `homm3 build` / `homm3 status update`. DO NOT HAND-EDIT.
# cur_fuzzy = current build; max_fuzzy = enforced ratchet; hist_fuzzy =
# all-time high (survives `update --accept-regressions`). Retail RVA carries
# history across source-label promotion and other same-body renames.
# unit<TAB>fn<TAB>cur_fuzzy<TAB>max_fuzzy<TAB>hist_fuzzy<TAB>rva
"""


@dataclass(frozen=True)
class MatchRow:
    cur: float | None
    max: float
    hist: float
    rva: int | None = None


def load_report() -> dict:
    executable = shutil.which("objdiff-cli")
    if not executable:
        common.die("objdiff-cli not found - enter the dev shell")
    result = subprocess.run([executable, "report", "generate",
                             "-o", "report.json"],
                            cwd=OBJDIFF_DIR, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write(result.stdout + result.stderr)
        common.die("objdiff-cli report generate failed")
    return json.loads(REPORT.read_text())


def fn_fuzzy(report: dict) -> dict:
    """(unit, fn) -> fuzzy_match_percent, for every function in the report."""
    return {
        (unit.get("name", "?"), fn.get("name", "?")):
            float(fn.get("fuzzy_match_percent") or 0.0)
        for unit in report.get("units", [])
        for fn in (unit.get("functions", []) or [])
    }


def load_baseline() -> dict[tuple[str, str], MatchRow]:
    rows = {}
    if BASELINE.is_file():
        for line in BASELINE.read_text().splitlines():
            if not line or line.startswith("#"):
                continue
            cols = line.split("\t")
            if len(cols) == 3:  # legacy unit/fn/max; update rewrites it
                unit, fn, value = cols
                score = float(value)
                rows[(unit, fn)] = MatchRow(score, score, score)
            elif len(cols) == 6:
                unit, fn, cur, maximum, historical, rva = cols
                rows[(unit, fn)] = MatchRow(
                    None if cur == "-" else float(cur),
                    float(maximum), float(historical),
                    None if rva == "-" else int(rva, 0))
            else:
                common.die(f"malformed {BASELINE.name} row: {line!r}")
    return rows


def historical_maxima_from_git() -> dict[tuple[str, str], float]:
    """Recover peaks from every tracked baseline revision during migration.

    `git log -p` exposes each value when it first enters the generated file,
    including maxima that legacy practice later lowered. This is deliberately
    read-only Git history: the status writer remains the sole TSV writer.
    """
    relative = BASELINE.relative_to(common.HOMM3_DIR)
    result = subprocess.run(
        ["git", "log", "-p", "--format=", "--", str(relative)],
        cwd=common.HOMM3_DIR, capture_output=True, text=True)
    if result.returncode != 0:
        return {}
    maxima = {}
    for patch_line in result.stdout.splitlines():
        if not patch_line.startswith("+") or patch_line.startswith("+++"):
            continue
        cols = patch_line[1:].split("\t")
        try:
            if len(cols) == 3:
                key, value = (cols[0], cols[1]), float(cols[2])
            elif len(cols) == 6:
                key, value = (cols[0], cols[1]), float(cols[4])
            else:
                continue
        except ValueError:
            continue
        maxima[key] = max(maxima.get(key, 0.0), value)
    return maxima


def seed_historical_maxima(rows: dict, maxima: dict) -> tuple[dict, int]:
    """Return rows with any recoverable pre-cur/max/hist peaks restored."""
    seeded, recovered = {}, 0
    for key, row in rows.items():
        historical = max(row.hist, maxima.get(key, 0.0))
        recovered += historical > row.hist + 1e-9
        seeded[key] = MatchRow(row.cur, row.max, historical, row.rva)
    return seeded, recovered


def function_rvas() -> dict[tuple[str, str], int]:
    """Current report identity, keyed by (unit, function label)."""
    if not SYMBOL_NAMES.is_file():
        return {}
    data = "\n".join(line for line in SYMBOL_NAMES.read_text().splitlines()
                     if not line.startswith("#"))
    out = {}
    for row in csv.DictReader(io.StringIO(data)):
        if row.get("kind") == "func":
            out[(row["unit"], row["name"])] = int(row["rva"], 0)
    return out


def load_baseline_comments() -> tuple:
    """Legacy rationale comments, anchored to the row they precede.

    Old revisions documented deliberate manual max-lowering in comments. The
    generated cur/max/hist format supersedes that practice, but automatic
    rewrites retain those historical explanations. The leading generated or
    legacy header block is excluded. Returns (anchored, trailing).
    """
    anchored, pending = {}, []
    if not BASELINE.is_file():
        return anchored, []
    seen_row = False
    for line in BASELINE.read_text().splitlines():
        if line.startswith("#"):
            # The leading block is generated metadata, including legacy header
            # text. Only comments embedded among data rows are historical notes.
            if not seen_row:
                continue
            pending.append(line)
        elif line:
            seen_row = True
            unit, fn = line.split("\t", 2)[:2]
            if pending:
                anchored[(unit, fn)] = pending
                pending = []
    return anchored, pending


def write_baseline(rows: dict[tuple[str, str], MatchRow]) -> None:
    anchored, trailing = load_baseline_comments()
    out = []
    for key in sorted(rows):
        out.extend(anchored.pop(key, ()))
        row = rows[key]
        cur = "-" if row.cur is None else f"{row.cur:.4f}"
        rva = "-" if row.rva is None else f"0x{row.rva:x}"
        out.append(f"{key[0]}\t{key[1]}\t{cur}\t{row.max:.4f}\t"
                   f"{row.hist:.4f}\t{rva}")
    # Comments whose row is gone (a promoted fn's flat-name row) outlive it:
    # dropping them is the very defect this function exists to prevent.
    for orphan in anchored.values():
        out.extend(orphan)
    out.extend(trailing)
    BASELINE.write_text(BASELINE_HEADER + "\n".join(out) + "\n")


def overall_line(report: dict) -> str:
    m = report.get("measures", {})
    total = int(m.get("total_functions") or 0)
    matched = int(m.get("matched_functions") or 0)
    fuzzy = float(m.get("fuzzy_match_percent") or 0.0)
    units = len(report.get("units", []))
    pct = 100.0 * matched / total if total else 0.0
    return (f"{matched}/{total} functions exact ({pct:.1f}%), "
            f"{fuzzy:.2f}% fuzzy across {units} unit(s)")


def cmd_summary(report: dict) -> int:
    print("  Unit        Funcs (exact)   Fuzzy")
    print("  " + "-" * 40)
    for unit in sorted(report.get("units", []),
                       key=lambda u: u.get("name", "")):
        m = unit.get("measures", {})
        total = int(m.get("total_functions") or 0)
        matched = int(m.get("matched_functions") or 0)
        fuzzy = float(m.get("fuzzy_match_percent") or 0.0)
        print(f"  {unit.get('name', '?'):<12} {matched:>3}/{total:<3}"
              f"      {fuzzy:>7.2f}%")
    print("  " + "-" * 40)
    print(f"  Overall: {overall_line(report)}")
    print(f"  Report: {REPORT}")
    return 0


def update_rows(current: dict, previous: dict, rvas: dict,
                accept_regressions: bool = False) -> tuple[dict, dict]:
    """Pure cur/max/hist update; stable RVA, not label, owns history."""
    by_rva = {}
    for key, row in previous.items():
        if row.rva is not None:
            by_rva.setdefault(row.rva, []).append((key, row))

    rows, consumed = {}, set()
    stats = {"added": 0, "raised": 0, "lowered": 0,
             "migrated": 0, "retired": 0}
    claimed_rvas = set(rvas.values())
    for key, raw_value in current.items():
        value = round(raw_value, 4)
        rva = rvas.get(key)
        old_key, old = key, previous.get(key)
        candidates = by_rva.get(rva, []) if rva is not None else []
        if len(candidates) == 1:
            old_key, old = candidates[0]
        elif old is not None and old.rva not in (None, rva):
            old = None  # this label now claims a different retail body

        if old is None:
            rows[key] = MatchRow(value, value, value, rva)
            stats["added"] += 1
            continue
        consumed.add(old_key)
        if old_key != key:
            stats["migrated"] += 1
        maximum = value if accept_regressions else max(old.max, value)
        historical = max(old.hist, old.max, value)
        if maximum > old.max + 1e-9:
            stats["raised"] += 1
        elif maximum < old.max - 1e-9:
            stats["lowered"] += 1
        rows[key] = MatchRow(value, maximum, historical,
                             rva if rva is not None else old.rva)

    for key, old in previous.items():
        if key in consumed or key in rows:
            continue
        if old.rva is not None and old.rva in claimed_rvas:
            continue
        # Old flat labels had no RVA. A missing 0% row records no matching
        # achievement, so label promotion may retire it without losing history.
        if old.rva is None and old.hist <= 1e-9:
            stats["retired"] += 1
            continue
        rows[key] = MatchRow(None, old.max, old.hist, old.rva)
    return rows, stats


def cmd_update(report: dict, accept_regressions: bool = False) -> int:
    previous = load_baseline()
    previous, recovered = seed_historical_maxima(
        previous, historical_maxima_from_git())
    rows, stats = update_rows(fn_fuzzy(report), previous, function_rvas(),
                              accept_regressions)
    write_baseline(rows)
    print("[status] baseline: "
          f"{stats['added']} added, {stats['migrated']} migrated, "
          f"{stats['raised']} max raised, {stats['lowered']} max accepted, "
          f"{recovered} historical peaks recovered, "
          f"{stats['retired']} empty legacy retired -> {BASELINE.name} "
          f"({len(rows)} rows)")
    return 0


def cmd_check(report: dict, gate: bool) -> int:
    rows = load_baseline()
    if not rows:
        print("[status] no baseline yet - run `homm3 status update`")
        return 0
    current = fn_fuzzy(report)
    drops = []
    for key, row in sorted(rows.items()):
        best = row.max
        value = current.get(key)
        if value is None:
            drops.append((key, best, None))
        elif value < best - EPS:
            drops.append((key, best, value))
    for (unit, fn), best, value in drops:
        now = f"{value:.2f}%" if value is not None else "MISSING"
        print(f"[status] REGRESSION {unit} {fn}: best {best:.2f}% -> {now}")
    if drops:
        print(f"[status] {len(drops)} function(s) below their recorded "
              "max. Review them, then use `homm3 status update "
              "--accept-regressions`; hist remains intact.")
        return 1 if gate else 0
    print(f"[status] ratchet clean ({len(rows)} functions at or above "
          "their recorded best)")
    return 0


def cmd_functions(report: dict, filters: list[str]) -> int:
    rows = load_baseline()
    current = fn_fuzzy(report)
    needles = [value.lower() for value in filters]
    print("  Cur       Max      Hist      RVA       Unit / function")
    print("  " + "-" * 78)
    for key in sorted(set(rows) | set(current)):
        haystack = f"{key[0]} {key[1]}".lower()
        if needles and not all(n in haystack for n in needles):
            continue
        row = rows.get(key)
        cur = current.get(key, row.cur if row else None)
        maximum = row.max if row else cur
        historical = row.hist if row else cur
        rva = row.rva if row else function_rvas().get(key)
        pct = lambda value: "    -   " if value is None else f"{value:7.2f}%"
        addr = "-" if rva is None else f"0x{rva:06x}"
        print(f"  {pct(cur)}  {pct(maximum)}  {pct(historical)}  "
              f"{addr:<8}  {key[0]} / {key[1]}")
    return 0


RM_START, RM_END = "<!-- match-score:start -->", "<!-- match-score:end -->"
README_PATH = common.HOMM3_DIR / "README.md"


def module_of(source: str) -> str:
    parts = Path(source).parts
    if parts and parts[0] == "vendor" and len(parts) > 1:
        return parts[1]
    if parts and parts[0] == "src":
        return "game"
    return parts[0] if parts else "?"


def _md_table(rows, align):
    widths = [max(len(r[i]) for r in rows) for i in range(len(rows[0]))]
    def fmt(row):
        cells = [c.ljust(w) if a == "l" else c.rjust(w)
                 for c, w, a in zip(row, widths, align)]
        return "| " + " | ".join(cells) + " |"
    sep = ["-" * w if a == "l" else "-" * (w - 1) + ":"
           for w, a in zip(widths, align)]
    out = [fmt(rows[0]), "| " + " | ".join(
        (":" + s[1:] if a == "l" else s)
        for s, a in zip(sep, align)) + " |"]
    out += [fmt(r) for r in rows[1:]]
    return out


def write_readme(report: dict) -> None:
    """Splice the per-module score table between the README sentinels
    (gruntz shape: Module | Units | Functions exact | Fuzzy | Fuzzy Max;
    Fuzzy Max weighs each function's best-ever from the baseline)."""
    from homm3.build.configure import load_manifest
    _build, _profiles, units = load_manifest()
    unit_module = {u["unit"]: module_of(u["source"]) for u in units}
    maxima = load_baseline()

    per_module = {}
    for unit in report.get("units", []):
        name = unit.get("name", "?")
        module = unit_module.get(name, name)
        agg = per_module.setdefault(
            module, {"units": 0, "fns": 0, "exact": 0, "wsum": 0.0,
                     "wmax": 0.0, "code": 0})
        agg["units"] += 1
        for fn in (unit.get("functions", []) or []):
            size = int(fn.get("size") or 0)
            fuzzy = float(fn.get("fuzzy_match_percent") or 0.0)
            row = maxima.get((name, fn.get("name", "?")))
            best = max(fuzzy, row.max if row else 0.0)
            agg["fns"] += 1
            agg["exact"] += fuzzy >= 100.0 - 1e-6
            agg["wsum"] += fuzzy * size
            agg["wmax"] += best * size
            agg["code"] += size

    # the full-engine denominator + excluded categories (single authority:
    # homm3.match.universe - every consumer uses it so filters cannot drift)
    from homm3.match import universe
    _category, _sizes, tally = universe.summary()
    target_fns = tally.get("target", (0, 0))[0]
    zlib_fns = tally.get("zlib", (0, 0))[0]
    covered = sum(a["fns"] for a in per_module.values())
    matched = sum(a["exact"] for a in per_module.values())
    denominator = target_fns + zlib_fns
    unmatched = denominator - covered

    rows = [["Module", "Units", "Functions exact", "Fuzzy", "Fuzzy Max"]]
    for module in sorted(per_module, key=lambda m: -per_module[m]["fns"]):
        a = per_module[module]
        pct = 100.0 * a["exact"] / a["fns"] if a["fns"] else 0.0
        fuzzy = a["wsum"] / a["code"] if a["code"] else 0.0
        fmax = a["wmax"] / a["code"] if a["code"] else 0.0
        rows.append([f"`{module}`", str(a["units"]),
                     f"{a['exact']} / {a['fns']} ({pct:.1f}%)",
                     f"{fuzzy:.2f}%", f"{fmax:.2f}%"])
    if unmatched:
        rows.append(["`(unmatched)`", "—",
                     f"0 / {unmatched:,} (0.0%)", "0.0%", "0.0%"])

    # the one-number scale: fuzzy-weighted matched bytes over ALL
    # unfiltered bytes (target + zlib retail extents; excluded categories
    # are not in either side of the fraction)
    unfiltered_bytes = (tally.get("target", (0, 0))[1]
                        + tally.get("zlib", (0, 0))[1])
    matched_bytes = sum(a["wsum"] for a in per_module.values()) / 100.0
    exe_pct = (100.0 * matched_bytes / unfiltered_bytes
               if unfiltered_bytes else 0.0)

    pct = 100.0 * matched / denominator if denominator else 0.0
    block = [RM_START, "",
             f"**Executable matched: {exe_pct:.2f}%** — fuzzy-weighted "
             f"bytes over all {unfiltered_bytes:,} unfiltered bytes.",
             "",
             f"**Match score** — {matched:,} / {denominator:,} functions "
             f"exact ({pct:.1f}%) across the full engine "
             f"({covered} in linked units).", ""]
    block += _md_table(rows, "lrrrr")

    excluded = [["Category", "Functions", "Code (B)", "Why excluded"]]
    labels = {"eh-funclet": "`EH unwind funclets`",
              "runtime": "`CRT/C++ runtime`",
              "init-thunk": "`init/cleanup thunks`",
              "import-thunk": "`import thunks`"}
    for cat, label in labels.items():
        fns, code = tally.get(cat, (0, 0))
        if fns:
            excluded.append([label, f"{fns:,}", f"{code:,}",
                             universe.EXCLUDED_NOTES[cat]])
    block += ["", "_Excluded from the % above — generated/library code, "
              "not independent reconstruction targets:_", ""]
    block += _md_table(excluded, "lrrl")
    block += ["", RM_END]

    text = README_PATH.read_text()
    if RM_START in text and RM_END in text:
        head, rest = text.split(RM_START, 1)
        _old, tail = rest.split(RM_END, 1)
        new = head + "\n".join(block) + tail
    else:
        lines = text.splitlines(keepends=True)
        at = next((i for i, l in enumerate(lines)
                   if l.startswith("## ")), len(lines))
        new = "".join(lines[:at]) + "\n".join(block) + "\n\n" \
            + "".join(lines[at:])
    if new != text:
        README_PATH.write_text(new)
        print("[status] README match-score block refreshed")
    print(f"[status] executable matched: {exe_pct:.2f}% "
          f"(fuzzy bytes / {unfiltered_bytes:,} unfiltered B)")


def main(argv=None) -> int:
    argv = list(argv if argv is not None else sys.argv[1:])
    gate = "--gate" in argv
    readme = "--write-readme" in argv
    accept = "--accept-regressions" in argv
    argv = [a for a in argv if a not in
            ("--gate", "--write-readme", "--accept-regressions")]
    command = argv[0] if argv else "summary"
    report = load_report()
    if readme:
        write_readme(report)
    if command == "summary":
        return cmd_summary(report)
    if command == "functions":
        return cmd_functions(report, argv[1:])
    if command == "update":
        return cmd_update(report, accept)
    if command == "check":
        return cmd_check(report, gate)
    print(f"usage: homm3 status [functions [FILTER...]|update "
          f"[--accept-regressions]|check [--gate]] [--write-readme] "
          f"(got {command!r})", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
