RM_START, RM_END = "<!-- match-score:start -->", "<!-- match-score:end -->"
README_PATH = common.HOMM3_DIR / "README.md"


def module_of(source: str) -> str:
    parts = Path(source).parts
    if parts and parts[0] == "vendor" and len(parts) > 1:
        return parts[1]
    if parts and parts[0] == "src":
        return "game"
    return parts[0] if parts else "?"


def _md_table(rows, align):
    widths = [max(len(r[i]) for r in rows) for i in range(len(rows[0]))]
    def fmt(row):
        cells = [c.ljust(w) if a == "l" else c.rjust(w)
                 for c, w, a in zip(row, widths, align)]
        return "| " + " | ".join(cells) + " |"
    sep = ["-" * w if a == "l" else "-" * (w - 1) + ":"
           for w, a in zip(widths, align)]
    out = [fmt(rows[0]), "| " + " | ".join(
        (":" + s[1:] if a == "l" else s)
        for s, a in zip(sep, align)) + " |"]
    out += [fmt(r) for r in rows[1:]]
    return out


def _previous_byte_accountability() -> str | None:
    try:
        text = README_PATH.read_text()
    except OSError:
        return None
    if RM_START not in text or RM_END not in text:
        return None
    block = text.split(RM_START, 1)[1].split(RM_END, 1)[0]
    return next((line for line in block.splitlines()
                 if line.startswith("**Byte accountability:**")), None)


def ledger_bodies(rows: dict) -> dict:
    """{retail RVA: (label, row)} - exactly one banked row per retail body.

    A complete `status update` retires a renamed body's old label, so a
    ledger naming one RVA twice is not a checkpoint the README can render.
    """
    bodies, duplicates = {}, {}
    for key, row in sorted(rows.items()):
        if row.rva is None:
            continue  # legacy flat label: no retail body to weigh
        if row.rva in bodies:
            duplicates.setdefault(row.rva, [bodies[row.rva][0]]).append(key)
            continue
        bodies[row.rva] = (key, row)
    if duplicates:
        rva, keys = min(duplicates.items())
        labels = ", ".join(f"{u} {f}" for u, f in keys)
        raise ValueError(f"retail RVA {rva:#x} has several banked labels ({labels}); "
                         f"run {COMPLETE_BUILD}, then `homm3 status update`")
    return bodies


def readme_block(rows: dict, *, data_accounting: dict | None = None,
                 previous_accountability: str | None = None) -> list[str]:
    """The README score block: a pure function of the banked ledger rows.

    Scores are the ledger's CUR/MAX/HIST. Byte weights, categories and the
    denominator come from the admitted retail inventory (config/retail/,
    keyed by RVA, via homm3.match.universe); modules from config/units.toml.
    No build output (objdiff report, symbol map, source fingerprints) is
    read, so every checkout renders the same block for the same ledger.
    """
    from homm3.build.configure import load_manifest
    _build, _profiles, units = load_manifest()
    unit_module = {u["unit"]: u.get("module", module_of(u["source"])) for u in units}
    # Numerators and denominator use the same retail universe.
    from homm3.match import universe
    category, sizes, tally = universe.summary()

    per_module = {}
    for rva, ((unit, _name), row) in sorted(ledger_bodies(rows).items()):
        if category.get(rva) not in ("target", "zlib"):
            continue
        size = sizes[rva]
        cur = row.cur or 0.0
        agg = per_module.setdefault(
            unit_module.get(unit, unit),
            {"units": set(), "fns": 0, "exact": 0, "exact_max": 0,
             "exact_hist": 0, "wsum": 0.0, "wmax": 0.0, "whist": 0.0,
             "code": 0})
        agg["units"].add(unit)
        agg["fns"] += 1
        agg["exact"] += cur >= 100.0 - 1e-6
        agg["exact_max"] += row.max >= 100.0 - 1e-6
        agg["exact_hist"] += row.hist >= 100.0 - 1e-6
        agg["wsum"] += cur * size
        agg["wmax"] += row.max * size
        agg["whist"] += row.hist * size
        agg["code"] += size

    def total(field):
        return sum(a[field] for a in per_module.values())

    denominator = (tally.get("target", (0, 0))[0]
                   + tally.get("zlib", (0, 0))[0])
    # The one-number scale: fuzzy-weighted matched bytes over ALL unfiltered
    # bytes (target + zlib retail extents; excluded categories are on
    # neither side of the fraction). Unbanked bodies weigh 0%.
    unfiltered_bytes = (tally.get("target", (0, 0))[1]
                        + tally.get("zlib", (0, 0))[1])
    unmatched = denominator - total("fns")

    def weighted(value: float) -> float:
        return value / unfiltered_bytes if unfiltered_bytes else 0.0

    table = [["Module", "Units", "Functions exact MAX", "Fuzzy MAX"]]
    for module in sorted(per_module, key=lambda m: (-per_module[m]["fns"], m)):
        a = per_module[module]
        table.append([f"`{module}`", str(len(a["units"])),
                      f"{a['exact_max']} / {a['fns']} "
                      f"({100.0 * a['exact_max'] / a['fns']:.1f}%)",
                      f"{a['wmax'] / a['code'] if a['code'] else 0.0:.2f}%"])
    if unmatched:
        table.append(["`(unmatched)`", "—", f"0 / {unmatched:,} (0.0%)", "0.0%"])

    exe_pct = weighted(total("wmax"))
    pct_max = 100.0 * total("exact_max") / denominator if denominator else 0.0
    block = [RM_START, "",
             f"**Windows `HEROES3.EXE`: {exe_pct:.2f}% matched (MAX)** — "
             f"{total('exact_max'):,} / {denominator:,} functions exact ({pct_max:.1f}%), "
             f"weighted by size over {unfiltered_bytes:,} bytes of code.", ""]
    block += _md_table([["Score", "Functions exact", "Weighted", "Meaning"],
                        ["CUR", f"{total('exact'):,}", f"{weighted(total('wsum')):.2f}%",
                         "last measured score"],
                        ["MAX", f"{total('exact_max'):,}", f"{exe_pct:.2f}%",
                         "best result for each function's current source"],
                        ["HIST", f"{total('exact_hist'):,}",
                         f"{weighted(total('whist')):.2f}%",
                         "all-time peak across source revisions"]], "lrrl")
    block += ["", "MAX by module:", ""]
    block += _md_table(table, "lrrr")

    excluded = [["Category", "Functions", "Code (B)", "Why excluded"]]
    labels = {"eh-funclet": "`EH unwind funclets`",
              "runtime": "`CRT/C++ runtime`",
              "init-thunk": "`init/cleanup thunks`",
              "import-thunk": "`import thunks`"}
    for cat, label in labels.items():
        fns, code = tally.get(cat, (0, 0))
        if fns:
            excluded.append([label, f"{fns:,}", f"{code:,}",
                             universe.EXCLUDED_NOTES[cat]])
    block += ["", "Excluded from the scores (generated or library code):", ""]
    block += _md_table(excluded, "lrrl")
    if data_accounting is not None:
        totals = data_accounting['totals']['file']
        initializers = data_accounting['initializers']
        exact = sum(row['verdict'] == 'exact' for row in initializers)
        dynamic = (data_accounting.get('source_initializers', {}).get('matches', [])
                   + data_accounting.get('startup_initializers', {}).get('matches', []))
        dynamic_summary = (f"{len(dynamic):,} source-emitted CRT bodies exact "
                           f"({sum(r['size'] for r in dynamic):,} bytes). "
                           if dynamic else "")
        unproven = (f"{totals.get('game-data-unverified', 0):,} unverified and "
                    f"{totals.get('game-data-mismatch', 0):,} mismatching game data bytes; "
                    f"{totals.get('game-data-pending-function', 0):,} bytes of exception "
                    f"records pending their functions' matches; "
                    f"{totals.get('padding', 0):,} bytes of reviewed padding. ")
        block += ["", f"**Byte accountability:** {totals.get('missing', 0):,} file bytes "
                  f"unclaimed; {totals.get('overlap', 0):,} bytes with conflicting claims; "
                  + unproven +
                  f"{exact:,} / {len(initializers):,} enrolled initializer comparisons exact. "
                  + dynamic_summary +
                  "[Data reports](docs/tooling/data-matching.md) separate ownership, "
                  "raw byte comparisons and verified library ranges."]
    elif previous_accountability:
        # Byte accounting is opt-in (`homm3 build --data`); keep its last
        # measured line rather than dropping it from the README.
        block += ["", previous_accountability]
    block += ["", RM_END]
    return block


def write_readme(*, data_accounting: dict | None = None,
                 rows: dict | None = None) -> None:
    """Splice the score block rendered from the ledger (default: the
    committed config/match_baseline.tsv) between the README sentinels.

    Run it after banking: the block shows what the ledger holds, never a
    local build report.
    """
    if rows is None:
        rows = load_baseline()
    block = readme_block(rows, data_accounting=data_accounting,
                         previous_accountability=_previous_byte_accountability())
    text = README_PATH.read_text()
    if RM_START in text and RM_END in text:
        head, rest = text.split(RM_START, 1)
        _old, tail = rest.split(RM_END, 1)
        new = head + "\n".join(block) + tail
    else:
        lines = text.splitlines(keepends=True)
        at = next((i for i, line in enumerate(lines)
                   if line.startswith("## ")), len(lines))
        new = "".join(lines[:at]) + "\n".join(block) + "\n\n" \
            + "".join(lines[at:])
    if new != text:
        README_PATH.write_text(new)
        print("[status] README match-score block refreshed from the ledger")
    print(f"[status] {block[2]}")


def build_parser():
    import argparse
    # Flags accepted before or after the subcommand, as they always were.
    # SUPPRESS keeps a subcommand's absent flag from erasing a global one.
    shared = argparse.ArgumentParser(add_help=False)
    shared.add_argument("--write-readme", action="store_true", default=argparse.SUPPRESS,
                        help="also regenerate the README score block from the "
                             "ledger (after `update` banks it)")
    shared.add_argument("--gate", action="store_true", default=argparse.SUPPRESS,
                        help=argparse.SUPPRESS)
    shared.add_argument("--accept-regressions", action="store_true",
                        default=argparse.SUPPRESS, help=argparse.SUPPRESS)
    raw = argparse.RawDescriptionHelpFormatter
    ap = argparse.ArgumentParser(prog="homm3 status", parents=[shared],
                                 description=__doc__, formatter_class=raw)
    sub = ap.add_subparsers(dest="command", metavar="COMMAND")
    sub.add_parser("summary", parents=[shared],
                   help="per-unit MAX table (the default)",
                   description="Per-unit projected MAX table. Read-only: when a "
                   "unit has unbuilt edits it shows the last measured report "
                   "and marks that unit with *.")

    fn = sub.add_parser(
        "functions", parents=[shared], formatter_class=raw,
        help="per-function MAX / CUR / HIST, with filters",
        description="Per-function scores: MAX and HIST are the banked "
        "checkpoint, CUR the last measured report. Read-only: units with "
        "unbuilt edits keep their last measured rows, marked * (and "
        "\"stale\": true in --json), with a warning naming the units.",
        epilog="examples:\n"
        "  homm3 status functions --unit hero --non-exact\n"
        "  homm3 status functions --va 0x00524dd0 --json\n"
        "  homm3 status functions completeDraw --below 95 --cur")
    fn.add_argument("filters", nargs="*", metavar="FILTER",
                    help="case-insensitive substring of 'unit function'; all must match")
    fn.add_argument("--unit", action="append", metavar="TU",
                    help="only this manifest unit (repeatable)")
    fn.add_argument("--va", action="append", metavar="ADDR",
                    help="only this retail VA (0x00524dd0) or RVA (repeatable)")
    fn.add_argument("--below", type=float, metavar="PCT",
                    help="only functions whose MAX (or CUR with --cur) is below PCT")
    fn.add_argument("--non-exact", action="store_true",
                    help="only functions below 100%% (same as --below 100)")
    fn.add_argument("--cur", action="store_true",
                    help="--below/--non-exact compare CUR instead of MAX")
    fn.add_argument("--json", action="store_true",
                    help="print the selected rows as JSON")

    up = sub.add_parser("update", parents=[shared],
                        help="bank current scores into config/match_baseline.tsv",
                        description="Refresh CUR and bank MAX/HIST for every unit "
                        "from one complete, fresh report. Banking is global (a "
                        "shared-header edit moves CUR in many units), so it "
                        "refuses while any unit is stale: run `homm3 build "
                        "--fast` (all units) first.")
    up.add_argument("--allow-ledger-loss", action="store_true",
                    help="bank rows even when they lower HIST, or MAX under an "
                         "unchanged source hash (normally kept, with a warning)")

    ck = sub.add_parser("check", parents=[shared],
                        help="classify source-edit MAX drops before banking",
                        description="Classify source-edit MAX drops against the "
                        "local or a committed ledger. Requires built sources: "
                        "it compares current source hashes with current scores.")
    ck.add_argument("--baseline-ref", metavar="REF",
                    help="compare with the ledger committed at REF")

    mb = sub.add_parser("merge-baseline", parents=[shared],
                        help="three-way merge of a conflicted ledger",
                        description="Merge Git's three conflict stages (or BASE "
                        "MAIN LANE revisions) of config/match_baseline.tsv.")
    mb.add_argument("revisions", nargs="*", metavar="REV",
                    help="BASE MAIN LANE revisions (default: Git's stages 1/2/3)")

    sn = sub.add_parser("snapshot", parents=[shared],
                        help="save per-function scores to a file for `status diff`",
                        description="Write measured CUR with projected MAX/HIST "
                        "for every function to FILE (JSON). Read-only for the ledger.")
    sn.add_argument("file", type=Path, metavar="FILE")
    sn.add_argument("--unit", action="append", metavar="TU",
                    help="only this unit (repeatable)")

    df = sub.add_parser("diff", parents=[shared],
                        help="per-function CUR/MAX changes against a ref or snapshot",
                        description="Compare the current scores (measured CUR, "
                        "projected MAX) with the ledger at a git revision or a "
                        "`status snapshot` file. Functions pair by retail RVA "
                        "across renames; kinds are improved, regressed, new, "
                        "removed (by CUR, then MAX).")
    df.add_argument("--against", required=True, metavar="REF|FILE",
                    help="snapshot file, else a git revision (e.g. origin/decomp-complete-4.0)")
    df.add_argument("--unit", action="append", metavar="TU",
                    help="only this unit (repeatable)")
    df.add_argument("--json", action="store_true", help="print JSON")
    df.add_argument("--all", action="store_true", help="also list unchanged functions")
    return ap


def main(argv=None) -> int:
    argv = list(argv if argv is not None else sys.argv[1:])
    try:
        args = build_parser().parse_args(argv)
    except SystemExit as exc:  # --help or a usage error
        return exc.code if isinstance(exc.code, int) else 2
    command = args.command or "summary"
    readme = getattr(args, "write_readme", False)
    if getattr(args, "accept_regressions", False):
        print("[status] --accept-regressions was removed: score peaks are "
              "checkpoints and are never lowered; source/evidence gates "
              "decide validity", file=sys.stderr)
        return 2
    if getattr(args, "gate", False):
        print("[status] --gate is obsolete: score checkpoints are "
              "observational")
    if command == "merge-baseline":
        from homm3.match import merge_baseline
        return merge_baseline.main(args.revisions)
    allow_loss = getattr(args, "allow_ledger_loss", False)

    def render_readme() -> None:
        # README is rendered from the ledger alone, never from a report.
        try:
            write_readme()
        except ValueError as exc:
            common.die(f"README score block not written: {exc}")

    if command == "update":
        # Banking is global: one complete, fresh report for every unit.
        require_complete_build()
        result = cmd_update(refresh_report(), allow_loss=allow_loss)
        if readme:
            render_readme()
        return result
    if readme:
        render_readme()
    if command == "check":
        # Judges current source hashes against current scores.
        require_built_sources()
        return cmd_check(refresh_report(), baseline_ref=args.baseline_ref)

    view = read_report_view()
    warn_stale(view)
    report, stale = view.report, view.stale
    if command == "summary":
        return cmd_summary(report, stale)
    from homm3.match import score_views
    view = ReportView(report, stale)
    units = set(getattr(args, "unit", None) or ())
    if command == "functions":
        return score_views.cmd_functions(view, args)
    if command == "snapshot":
        return score_views.cmd_snapshot(view, args.file, units)
    return score_views.cmd_diff(view, args.against, units=units,
                                as_json=args.json, show_all=args.all)


if __name__ == "__main__":
    sys.exit(main())
