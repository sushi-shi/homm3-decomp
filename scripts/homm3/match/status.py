#!/usr/bin/env python3
"""homm3.match.status - the objdiff scoreboard and checkpoint ledger.

  homm3 status           per-unit table + overall (on-demand human view;
                         never printed by the build tail - gruntz doctrine)
  homm3 status functions [FILTER...] [--unit TU] [--va ADDR] [--below PCT]
                         [--non-exact] [--cur] [--json]
                         per-function current / max / historical scores
  homm3 status snapshot FILE [--unit TU]
  homm3 status diff --against REF|FILE [--unit TU] [--json] [--all]
                         per-function CUR/MAX before vs after: improved,
                         regressed, new and removed functions
  homm3 status update [--write-readme]
                         refresh current scores; MAX is the high-water for the
                         current source hash, HIST is the all-time high.
                         Banking is global (a shared-header edit moves CUR in
                         many units), so every unit must be built and fresh.
  homm3 status check [--baseline-ref REF]
                         classify source-edit MAX drops before banking;
                         unrelated CUR movement is silent and scores remain
                         observational
  homm3 status merge-baseline [BASE MAIN LANE]
                         merge concurrent checkpoint ledgers three ways

Read-only views (summary, functions, snapshot, diff) never refuse because a
unit has unbuilt edits: they show the last measured report, mark that unit's
rows with *, and name the `homm3 build --fast` that refreshes them. update
and check bank or judge, so they require built sources. --write-readme renders
the README score block from the committed ledger alone (after update banks it).

Baseline: config/match_baseline.tsv, generated by this module. Stable retail
RVAs carry cur/max/hist across flat-name -> decorated-name promotion. Legacy
three-column rows are migrated automatically; a missing zero-score legacy row
is retired because it contains no historical match evidence. Per-function
source hashes distinguish an edited implementation from an old banked dip or
collateral codegen movement. The stored invariant is CUR <= MAX <= HIST: MAX
preserves the best score reached by the current implementation, while HIST
preserves peaks reached by older implementations. A lower score is not evidence
that the source change is wrong: the Dreamcast/source/retail gates decide
admissibility. The report is regenerated fresh each call.
"""
