"""homm3 census - the function, vtable and relocation census of an image.

    homm3 --image h3maped census [--write] [--check]

Reads the selected image's pinned executable and derives:

  functions.tsv   rva, size: the function universe (homm3.census.functions);
  vtables.tsv     rva, function_count, class (homm3.census.vtables);
  reloc-evidence.tsv  every candidate site with its value, channel, target
                  class and disposition (the model names data targets);
  relocs.tsv      site_rva, kind: absolute-relocation sites for vostok's
                  --reloc-manifest, from the vendored find_relocs channels
                  (code operands, switch tables, data dwords outside
                  literals) with data pointers into a function's interior
                  dropped against the function census;
  funclets.tsv    rva, parent_rva, state: EH funclets and the function
                  whose `__ehhandler` stub names their FuncInfo; with the
                  pin's `census_folds_catch_handlers`, a catch handler that
                  directly follows its parent is part of the parent's
                  functions.tsv extent instead (the game's rule), and the
                  census reports the handlers it leaves as rows; with
                  `census_joins_tails`, a piece the census cut off at a
                  jump target joins the function before it (homm3.census.
                  functions.merges) and the census reports each candidate
                  it leaves as a row;
  init-thunks.tsv rva, slot: the `.CRT$XCU` initializer table, the body
                  after each `/O1` `jmp $+5` slot thunk, and the cleanups
                  those initializers register with `_atexit` (slot -);
  runtime-map.tsv rva, name, library, member: statically linked library
                  functions named by unique masked identity with a member
                  of LIBCMT, LIBCPMT or the staged SP3 MFC NAFXCW
                  (homm3.census.libraries); named, not matched;
  runtime-aliases.tsv rva, name, library, member: the other members of an
                  identical-code fold the runtime map names once.

Without --write it prints the counts. --write stores the tables under the
image's config/retail/<image>/ (with an image-hash banner) and creates the
empty reviewed provider tables the label model reads. --check compares the
derived tables with the committed ones and fails on any difference. The
game's census is hand-owned (config/retail/*.tsv) and never regenerated.
"""
from __future__ import annotations

import argparse
import sys

from homm3.core import common, paths

GENERATOR = "homm3.census"
BANNER = [
    "# GENERATED by `homm3 --image {image} census --write` from the pinned",
    "# executable; regenerate rather than hand-edit. Reviewed corrections",
    "# belong in the image's reviewed tables, never in these rows.",
]

#: Reviewed provider tables the model reads, created empty with their header.
EMPTY_TABLES = {
    "zlib-map.tsv": "rva\tsize\tname\tunit\tkind",
    "reloc-aliases.tsv": "function_rva\ttarget_rva\tsite_rva\towner\taddend\toccurrences",
    "runtime-contributions.tsv": "rva\tsize\tkind\tlibrary\tmember\tsection\tsymbol\tevidence",
}


def pin_flag(name: str, image: str | None = None) -> bool:
    """A census switch on the image's config/project.toml pin."""
    from homm3.core import images
    key = image or paths.image_key()
    return bool(images.pins(paths.ROOT).get(images.input_key(key), {}).get(name, False))


def folds_catch_handlers(image: str | None = None) -> bool:
    """Whether the image's census folds catch handlers into their parents
    (`census_folds_catch_handlers`)."""
    return pin_flag("census_folds_catch_handlers", image)


def joins_tails(image: str | None = None) -> bool:
    """Whether the image's census joins the pieces it cut off at a jump
    target to the function before them (`census_joins_tails`)."""
    return pin_flag("census_joins_tails", image)


def joins_catch_bodies(image: str | None = None) -> bool:
    """Whether the image's census keeps a function's code on both sides of
    its catch blocks one function (config/project.toml
    `census_joins_catch_bodies` on the image's pin; see
    functions.Census.tail_limit)."""
    return pin_flag("census_joins_catch_bodies", image)


def tail_alignment(image: str | None = None) -> int:
    """The function alignment a joined tail may not start on
    (`census_tail_alignment`; 0: none, as /O1 pads no function)."""
    from homm3.core import images
    key = image or paths.image_key()
    return int(images.pins(paths.ROOT).get(images.input_key(key), {})
               .get("census_tail_alignment", 0))


def derive(log=print):
    from homm3.core.image import Image
    from homm3.census import find_relocs, functions, vtables
    image = Image(str(common.resolve_exe()))
    census = functions.run(image, log=log, catch_bodies=joins_catch_bodies())
    from homm3.census import eh
    folded = {}
    catches, tails = folds_catch_handlers(), joins_tails()
    if catches or tails:
        folded, refused = functions.merges(census, eh.funcinfo_parents(census),
                                           catches=catches, tails=tails,
                                           alignment=tail_alignment())
        for kind, verb in (("catch", "catch handlers folded into their parents"),
                           ("tail", "tails joined to the function before them")):
            if not (catches if kind == "catch" else tails):
                continue
            count = sum(1 for piece in folded if (piece in census.funclets) == (kind == "catch"))
            left = [row for row in refused if row[2] == kind]
            log(f"[census] {count} {verb}, {len(left)} left as rows")
            if kind == "tail":
                for piece, owner in sorted(folded.items()):
                    if piece not in census.funclets:
                        log(f"[census]   tail 0x{piece:x} joined to 0x{owner:x}")
            for piece, owner, _kind, reason in left:
                who = f"0x{owner:x}" if owner is not None else "-"
                log(f"[census]   {kind} 0x{piece:x} (owner {who}) not merged: {reason}")
    rows = functions.partition(census, folded)
    # a folded handler is no function, but the FuncInfo still points at it
    starts = {rva for rva, _size, _reached in rows} | set(folded)
    vt = vtables.census(census, starts)

    sites, masks = {}, {}
    for section in image.sections:
        if section.name in (".rsrc", ".reloc"):
            continue
        if section.executable:
            sites.update(find_relocs.code_sites(image, section, walk_tables=True))
        else:
            masks[section.name] = find_relocs.literal_mask(image.blob(section))
            sites.update(find_relocs.data_sites(image, section))
    neighbours = frozenset(rva for rva, site in sites.items() if site.channel == "data")
    kept, dropped, evidence = [], 0, []
    for rva, site in sorted(sites.items()):
        klass = find_relocs.target_class(image, site, masks, starts, neighbours)
        drop = klass == "unmapped" or (site.channel == "data" and klass == "code-interior")
        evidence.append(f"0x{rva:x}\t0x{site.target:x}\t{site.channel}\t{site.detail}"
                        f"\t{klass}\t-\t{'dropped' if drop else 'kept'}")
        if drop:
            dropped += 1
            continue
        kept.append(rva)
    from homm3.census import libraries
    funclets, orphans = eh.funclet_rows(census, folded)
    thunks = eh.initializer_rows(census)
    toolchain = paths.msvc_dir() / "lib"
    archives = {"LIBCMT": toolchain / "LIBCMT.LIB", "LIBCPMT": toolchain / "LIBCPMT.LIB",
                "NAFXCW": paths.SHARED_BUILD / "mfc-sp3/lib/nafxcw.lib"}
    from homm3.retail_labels.iat import iat_slots
    imports = {name: slot for slot, (name, _channel)
               in iat_slots(common.resolve_exe(), toolchain).items()}
    classes = {c: r for r, _n, c in vt if c and not c.startswith("??_7")}
    aliases = []
    runtime = libraries.derive(image, {r: s for r, s, _ in rows}, archives, log=log,
                               imports=imports, vtables=classes, aliases=aliases)
    # reviewed names for identical library members the bytes cannot tell apart
    from homm3.core.tsv import read as read_tsv
    named = {r for r, _n, _l, _m in runtime}
    reviewed = paths.retail_dir() / "runtime-contributions.tsv"
    if reviewed.is_file():
        starts = {r for r, _s, _d in rows}
        names_at = {r: n for r, n, _l, _m in runtime}
        for row in read_tsv(reviewed)[2]:
            rva = int(row["rva"], 16)
            if row["kind"] != "code" or rva not in starts:
                continue
            library = row["library"].rsplit(".", 1)[0]
            if rva not in names_at:
                runtime.append((rva, row["symbol"], library, row["member"]))
                names_at[rva] = row["symbol"]
            elif names_at[rva] != row["symbol"]:
                # another member of an identical-code fold the row's
                # evidence reviews
                aliases.append((rva, row["symbol"], library, row["member"]))
        runtime.sort()
        aliases.sort()
    atexit = next((r for r, n, _l, _m in runtime if n == "_atexit"), None)
    if atexit is not None:
        thunks += eh.cleanup_rows(census, {r for r, _k in thunks}, atexit)
    log(f"[census] {len(funclets)} funclets with parents ({orphans} without), "
        f"{len(thunks)} .CRT$XCU initializers")
    log(f"[census] {len(rows)} functions, {len(vt)} vtables "
        f"({sum(1 for v in vt if v[2])} named), {len(kept)} relocation sites "
        f"({dropped} dropped: unmapped or data into a function interior)")
    return {
        "functions.tsv": ("rva\tsize", [f"0x{r:x}\t{s}" for r, s, _ in rows]),
        "vtables.tsv": ("rva\tfunction_count\tclass",
                        [f"0x{r:x}\t{n}\t{c}" for r, n, c in vt]),
        "relocs.tsv": ("site_rva\tkind", [f"0x{r:x}\tdir32" for r in kept]),
        "reloc-evidence.tsv": ("site_rva\tvalue\tchannel\tdetail\ttarget_class\tctx"
                               "\tdisposition", evidence),
        "funclets.tsv": ("rva\tparent_rva\tstate",
                         [f"0x{r:x}\t0x{p:x}\t{st}" for r, p, st in funclets]),
        "init-thunks.tsv": ("rva\tslot", [f"0x{r:x}\t{k}" for r, k in thunks]),
        "runtime-map.tsv": ("rva\tname\tlibrary\tmember",
                            [f"0x{r:x}\t{n}\t{lib}\t{m}" for r, n, lib, m in runtime]),
        "runtime-aliases.tsv": ("rva\tname\tlibrary\tmember",
                                [f"0x{r:x}\t{n}\t{lib}\t{m}" for r, n, lib, m in aliases]),
    }


def render(image: str, header: str, rows: list[str]) -> str:
    lines = [line.format(image=image) for line in BANNER]
    lines += common.provenance(GENERATOR)
    return "\n".join(lines + [header] + rows) + "\n"


def body(text: str) -> list[str]:
    return [line for line in text.splitlines() if not line.startswith("#")]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(prog="homm3 census", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true",
                        help="store the derived tables under config/retail/<image>/")
    parser.add_argument("--check", action="store_true",
                        help="fail when the committed tables differ from the derivation")
    args = parser.parse_args(argv)
    image = paths.image_key()
    if paths.is_game(image):
        print("[census] the game's census is hand-owned (config/retail/*.tsv); "
              "select another image with `homm3 --image KEY census`", file=sys.stderr)
        return 1
    tables = derive()
    directory = paths.retail_dir(image)
    if args.check:
        stale = [name for name, (header, rows) in tables.items()
                 if not (directory / name).is_file()
                 or body((directory / name).read_text()) != [header, *rows]]
        for name in stale:
            print(f"[census] {directory / name} differs from the derivation", file=sys.stderr)
        return 1 if stale else 0
    if args.write:
        directory.mkdir(parents=True, exist_ok=True)
        for name, (header, rows) in tables.items():
            (directory / name).write_text(render(image, header, rows))
        for name, header in EMPTY_TABLES.items():
            path = directory / name
            if not path.exists():
                path.write_text(f"# REVIEWED rows for the {image} image; none admitted yet.\n"
                                f"{header}\n")
        print(f"[census] wrote {', '.join(tables)} -> {directory.relative_to(paths.ROOT)}")
    return 0


def logged_main(argv=None) -> int:
    from homm3.core.usage import append, run_logged
    import shlex
    argv = list(sys.argv[1:] if argv is None else argv)
    cmd = shlex.join(["homm3", f"--image={paths.image_key()}", "census", *argv])
    return run_logged(main, argv,
                      lambda rc, **meta: append(paths.SHARED_BUILD / "homm3_usage.log",
                                                cmd, rc, **meta), failure_rc=1)


if __name__ == "__main__":
    sys.exit(logged_main())
