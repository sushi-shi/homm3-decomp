"""Score ledger and README block of the Loki h3maped image.

    config/loki/match_baseline.tsv   one row per banked project function
    README.md                        <!-- loki-match-score:start/end --> block

The ledger has the game's CUR <= MAX <= HIST schema. A row's fingerprint is
the SHA-1 of the compiled function in its canonical comparison form (bytes,
relocation targets and addends): g++ 2.95 at -O0 compiles a function from its
own source alone, so the emitted body stands in for the source hash. MAX
holds while the fingerprint holds and resets to CUR when it changes; HIST
keeps the all-time peak.

The README block renders from the ledger and the census alone, never from a
build report. Its denominator is every project function: the .text functions
and the kept linkonce bodies (templates, inline members, SGI instantiations)
of the 103 GCC 2.95.2 project objects. The C libraries and libstdc++ are not
counted. The engine phase is the object list in config/loki/units.toml
`[phases]`.

Data rows (name `$data`, address = the object ordinal) bank each unit's
data comparison (homm3.loki.datacmp): size is the image's data bytes in
the object's slices, cur/max/hist count matching bytes, and the
fingerprint hashes the compiled data sections with their relocations.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import tomllib

from homm3.core import common
from homm3.loki import cmpobj
from homm3.loki.cmpobj import CodeSection

ROOT = common.HOMM3_DIR
LEDGER = ROOT / "config/loki/match_baseline.tsv"
README = ROOT / "README.md"
START, END = "<!-- loki-match-score:start -->", "<!-- loki-match-score:end -->"
DATA = "$data"
HEADER = ("# GENERATED by `homm3 loki build --bank`. Do not hand-edit.\n"
          "# Invariant: cur <= max <= hist; max resets when the fingerprint changes.\n"
          "# Rows named $data are a unit's data bytes: address = object, size = image bytes,\n"
          "# cur/max/hist = matching bytes (homm3.loki.datacmp).\n"
          "# address\tobject\tunit\tname\tsize\tcur\tmax\thist\tfingerprint\n")


@dataclass
class Row:
    address: int
    obj: int
    unit: str
    name: str
    size: int
    cur: float
    max: float
    hist: float
    fingerprint: str

    def line(self) -> str:
        return (f"{self.address:08x}\t{self.obj}\t{self.unit}\t{self.name}\t{self.size}\t"
                f"{self.cur:.4f}\t{self.max:.4f}\t{self.hist:.4f}\t{self.fingerprint}")


def load() -> dict[int, Row]:
    rows = {}
    if not LEDGER.exists():
        return rows
    for line in LEDGER.read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        address, obj, unit, name, size, cur, high, hist, fingerprint = line.split("\t")
        rows[int(address, 16)] = Row(int(address, 16), int(obj), unit, name, int(size),
                                     float(cur), float(high), float(hist), fingerprint)
    return rows


def save(rows: dict[int, Row]) -> None:
    LEDGER.write_text(HEADER + "".join(rows[a].line() + "\n" for a in sorted(rows)))


def fingerprints(base: list[CodeSection]) -> dict[str, str]:
    """Canonical name -> SHA-1 of the compiled function's comparison form."""
    out = {}
    for section in base:
        relocs = sorted(section.relocs, key=lambda r: r.offset)
        for function in section.functions:
            end = function.offset + function.size
            digest = hashlib.sha1(bytes(section.data[function.offset:end]))
            for reloc in relocs:
                if function.offset <= reloc.offset < end:
                    digest.update(f"{reloc.offset - function.offset}:{reloc.type}:"
                                  f"{cmpobj.canonical_symbol(reloc.target)}:{reloc.addend};".encode())
            out[cmpobj.canonical_symbol(function.name)] = digest.hexdigest()[:12]
    return out


def bank(rows: dict[int, Row], unit: str, obj: int, target: list[CodeSection],
         scores: dict[str, float], prints: dict[str, str]) -> None:
    """Update the rows of one built unit from its objdiff scores."""
    for section in target:
        for function in section.functions:
            name = cmpobj.canonical_symbol(function.name)
            cur = round(scores.get(name, 0.0), 4)
            fingerprint = prints.get(name, "-")
            old = rows.get(function.address)
            if old is None:
                rows[function.address] = Row(function.address, obj, unit, name, function.size,
                                             cur, cur, cur, fingerprint)
                continue
            same = old.fingerprint == fingerprint and fingerprint != "-"
            old.unit, old.name, old.size = unit, name, function.size
            old.cur = cur
            old.max = max(old.max, cur) if same else cur
            old.hist = max(old.hist, old.max)
            old.fingerprint = fingerprint


def bank_data(rows: dict[int, Row], unit: str, obj: int, matched: int, total: int,
              fingerprint: str) -> None:
    """Update a unit's data row: matching bytes of its data slices."""
    old = rows.get(obj)
    if old is None or old.name != DATA:
        rows[obj] = Row(obj, obj, unit, DATA, total, matched, matched, matched, fingerprint)
        return
    # A slice that changed size (a neighbour moved) is a new denominator.
    resized = old.size != total
    same = old.fingerprint == fingerprint and not resized
    old.unit, old.size, old.cur = unit, total, matched
    old.max = max(old.max, matched) if same else matched
    old.hist = old.max if resized else max(old.hist, old.max)
    old.fingerprint = fingerprint


def data_rows(rows: dict[int, Row]) -> list[Row]:
    return [row for row in rows.values() if row.name == DATA]


def phases() -> dict[str, set[int]]:
    with (ROOT / "config/loki/units.toml").open("rb") as stream:
        return {name: set(objects) for name, objects in tomllib.load(stream).get("phases", {}).items()}


def readme_block(rows: dict[int, Row]) -> list[str]:
    from homm3.loki.delink import RETAIL, census
    project = {int(line.split("\t")[0]) for line in (RETAIL / "objects.tsv").read_text().splitlines()
               if not line.startswith("#") and line.split("\t")[1] == "project"}
    functions = [f for f in census() if f.obj in project]
    groups = phases()
    engine = groups.get("engine", set())

    def measure(members) -> tuple[int, int, int, float, float, float]:
        exact = [0, 0, 0]
        weighted = [0.0, 0.0, 0.0]
        size = 0
        for f in members:
            size += f.size
            row = rows.get(f.address)
            if row is None:
                continue
            for i, value in enumerate((row.cur, row.max, row.hist)):
                exact[i] += value >= 100.0
                weighted[i] += value * f.size
        total = size or 1
        return (*exact, *(w / total for w in weighted))

    data = data_rows(rows)

    def data_measure(objects) -> tuple[int, int, int, int]:
        members = [r for r in data if r.obj in objects]
        return (sum(int(r.cur) for r in members), sum(int(r.max) for r in members),
                sum(int(r.hist) for r in members), sum(r.size for r in members))

    def row(label: str, members: list) -> str:
        objs = {f.obj for f in members}
        _c, exact, _h, _cf, fuzzy, _hf = measure(members)
        _dc, matched, _dh, size = data_measure(objs)
        cells = (f"| {label} | {len(objs)} | {exact:,} / {len(members):,} "
                 f"({100 * exact / max(1, len(members)):.1f}%) | {fuzzy:.2f}% |")
        return cells + (f" {matched:,} / {size:,} ({100 * matched / max(1, size):.2f}%) |" if data else "")

    cur, high, hist, cur_f, max_f, hist_f = measure(functions)
    total = len(functions)
    text = sum(1 for f in functions if not f.linkonce)
    units = len({r.unit for r in rows.values()})
    d_cur, d_max, d_hist, d_size = data_measure(project)
    # Until a build banks data rows the block keeps its function-only shape.
    headline = (f" &middot; {d_max:,} / {d_size:,} data bytes ({100 * d_max / max(1, d_size):.2f}%)"
                if data else "")
    return [
        START, "",
        "**Loki Linux `h3maped` 1.0 (map editor, GCC 2.95.2): "
        f"{high:,} / {total:,} functions exact ({100 * high / max(1, total):.2f}%) "
        f"&middot; {max_f:.2f}% fuzzy{headline} (MAX).**",
        "",
        "A separate image with its own scores; `homm3 loki build --bank` banks "
        "`config/loki/match_baseline.tsv`, and this block renders from it.",
        "",
        "| Phase | Objects | Functions exact MAX | Fuzzy MAX |" + (" Data bytes MAX |" if data else ""),
        "| :---- | ------: | ------------------: | --------: |" + (" -------------: |" if data else ""),
        row("engine (shared with the game)", [f for f in functions if f.obj in engine]),
        row("editor", [f for f in functions if f.obj not in engine]),
        "",
        f"_CUR / MAX / HIST: {cur:,} / {high:,} / {hist:,} exact &middot; "
        f"{cur_f:.2f}% / {max_f:.2f}% / {hist_f:.2f}% fuzzy, weighted by size"
        + (f" &middot; {d_cur:,} / {d_max:,} / {d_hist:,} data bytes. " if data else ". ") +
        f"Project functions only: the {text:,} `.text` functions and {total - text:,} kept "
        f"linkonce bodies of the {len(project)} GCC 2.95.2 project objects "
        f"({units} built units); GTK+/glib/libglade/libxml/zlib and libstdc++ are excluded."
        + (" Data bytes are the objects' `.rodata`, `.data`, `.bss`, `.gcc_except_table`, "
           "`.ctors`/`.dtors` slices of the image, their kept linkonce data (vtables) and COMMON "
           "type_info nodes, relocations resolved; jump tables count with their functions." if data else "")
        + "_",
        "", END,
    ]


def write_readme(rows: dict[int, Row] | None = None, path=None) -> bool:
    """Splice the Loki block into README.md (or `path`); True when it changed.
    A README without the Loki sentinels is left alone."""
    path = README if path is None else path
    rows = load() if rows is None else rows
    text = path.read_text()
    if text.count(START) != 1 or text.count(END) != 1:
        return False
    head, rest = text.split(START, 1)
    _old, tail = rest.split(END, 1)
    new = head + "\n".join(readme_block(rows)) + tail
    if new != text:
        path.write_text(new)
        return True
    return False
