"""Per-function verdicts for the code the README keeps outside the scores.

The score denominator is game and zlib code (`homm3.match.universe`). The
other census rows are library or compiler-generated code. They still have to
be accounted for, function by function, against what produced them:

`runtime`       LIBCMT/LIBCPMT bodies. Each function lies in one or more COFF
                sections that `config/retail/runtime-contributions.tsv` places
                and `homm3 verify library-code` proves (bytes plus every
                relocation target). The function is verified when every byte
                lies in exact contributions (or in the 0xCC link fill between
                two of them).
`eh-funclet`    `/GX` unwind funclets. Library parents' funclets lie in the
                library contributions above. A game parent's funclets and its
                registration stub are its associative `.text$x` COMDAT; that
                candidate section is compared with the retail group from the
                first funclet outside the parent to the stub's end: every
                unrelocated byte, the retail relocation sites, and every
                relocation target (the destructor, `___CxxFrameHandler`, the
                FuncInfo the stub loads, local labels) resolved by name.
`init-thunk`    `.CRT$XCU` dynamic initializers and their atexit cleanups:
                the source, startup, shared-header and local-cleanup
                comparisons of `homm3.verify.byte_accounting` (raw COFF bytes
                and named relocations, nothing masked).
`import-thunk`  `jmp [__imp_X]` stubs (`homm3.verify.import_thunks`).

Verdicts never feed the game's per-function scores. They are banked in two
tables that the README reads:

* `config/retail/runtime-functions.tsv` - each runtime function, its library
  object(s) and verdict. Pinned libraries and retail bytes decide it, so it
  is a retail fact; `--check` re-proves it.
* `config/generated_code_baseline.tsv` - the funclet, initializer and import
  thunk verdicts, which depend on the current game objects; `homm3 build`
  banks them like the score ledger.

    homm3 verify generated-code            summary per category
    homm3 verify generated-code --write    rewrite both tables
    homm3 verify generated-code --check    nonzero when a table is stale
    homm3 verify generated-code --findings non-exact rows
"""

from __future__ import annotations

import bisect
import struct
import sys
from collections import Counter, defaultdict
from pathlib import Path

from homm3.core import msvc_names
from homm3.core.paths import RETAIL, ROOT
from homm3.core.tsv import read, write

RUNTIME_TABLE = RETAIL / 'runtime-functions.tsv'
BASELINE = ROOT / 'config/generated_code_baseline.tsv'
CATEGORIES = ('runtime', 'eh-funclet', 'init-thunk', 'import-thunk')
DIR32, REL32 = 6, 20
FILL = 0xCC

RUNTIME_BANNER = [
    '# GENERATED by `homm3 verify generated-code --write`; `--check` re-proves it.',
    '# One row per census function in the CRT/C++ runtime band',
    '# (config/retail/runtime-map.tsv): the pinned VC6 SP3 library object(s)',
    '# whose COFF sections hold its bytes (config/retail/runtime-contributions.tsv',
    '# placements) and the verdict of `homm3 verify library-code` on them.',
    '# `exact`: every byte lies in byte- and relocation-verified sections or',
    '# the 0xCC link fill between them. `sections` lists member#section for',
    '# each covering contribution; `symbol` is the first one\'s symbol.',
    '# `name` is the runtime-map label; the linker symbol is `symbol`.',
]
BASELINE_BANNER = [
    '# GENERATED by `homm3 build` (`homm3 verify generated-code --write`).',
    '# DO NOT HAND-EDIT. Compiler-generated census functions outside the score',
    '# denominator: EH unwind funclets (verified with their parent\'s `.text$x`',
    '# contribution or the library section holding them), CRT initializer and',
    '# cleanup bodies, and linker import thunks. These verdicts never change a',
    '# game function\'s CUR/MAX/HIST.',
]


# ---------------------------------------------------------------- runtime --

def runtime_verdicts(pe, census, category, verdicts):
    """[(row dict)] for every `runtime` census function."""
    placed = sorted(((v.row.rva, v.row.rva + max(v.row.size, 1 if v.row.kind == 'thunk' else 0), v)
                     for v in verdicts
                     if v.row.kind in ('code', 'alias', 'thunk') and v.row.library != 'zlib'),
                    key=lambda item: item[:2])
    starts = [lo for lo, _hi, _v in placed]
    names = _runtime_names()
    out = []
    for rva in sorted(r for r, c in category.items() if c == 'runtime'):
        size = census[rva]
        end = rva + size
        k = max(bisect.bisect_right(starts, rva) - 1, 0)
        hits = []
        while k < len(placed) and placed[k][0] < end:
            lo, hi, v = placed[k]
            if hi > rva:
                hits.append((lo, hi, v))
            k += 1
        verdict, reason = 'exact', ''
        if not hits:
            verdict, reason = 'unplaced', 'no library contribution covers it'
        else:
            pos = rva
            for lo, hi, v in hits:
                if lo > pos:
                    gap = pe.read(pos, lo - pos)
                    if pos == rva or gap != bytes([FILL]) * (lo - pos):
                        verdict, reason = 'unplaced', f'{lo - pos} byte(s) at {pos:#x} uncovered'
                        break
                if v.verdict != 'exact':
                    verdict = v.verdict
                    reason = '; '.join(v.reasons[:2])
                    break
                pos = max(pos, hi)
            else:
                if pos < end:
                    verdict, reason = 'unplaced', f'{end - pos} byte(s) at {pos:#x} uncovered'
        first = hits[0][2].row if hits else None
        out.append(dict(
            rva=f'{rva:#x}', size=str(size), name=names.get(rva, ''),
            library=first.library if first else '-',
            member=first.member if first else '-',
            sections=';'.join(f'{v.row.member}#{v.row.section}' if v.row.kind != 'thunk'
                              else f'{v.row.library}:import-thunk'
                              for _lo, _hi, v in hits) or '-',
            symbol=first.symbol if first else '-',
            verdict=verdict + (f' ({reason})' if reason and verdict != 'exact' else '')))
    return out


def _runtime_names():
    _b, _h, rows = read(RETAIL / 'runtime-map.tsv')
    return {int(r['rva'], 16): r['name'] for r in rows}


# ------------------------------------------------------------- EH funclets --

def _names(model, enrolled, library_names):
    names = defaultdict(set)
    for b in model.functions + model.data:
        for entry in (b, *b.aliases):
            if entry.name and entry.channel:
                key = msvc_names.mask(entry.name)
                names[('', key)].add(b.rva)
                if entry.unit:
                    names[(entry.unit, key)].add(b.rva)
    for r in enrolled:
        if 'gap' not in r.get('provenance', ''):
            key = msvc_names.mask(r['name'])
            names[('', key)].add(int(r['rva'], 0))
            names[(r['object'].removesuffix('.c'), key)].add(int(r['rva'], 0))
    for rva, symbols in library_names.items():
        for symbol in symbols:
            names[('', symbol)].add(rva)
    return names


def funclet_group(group, name, unit, loaded, objects, pe, image, names, parent_size,
                  comdats=None):
    """(verdict, reason, start) for one game parent's `.text$x` contribution.

    A relocation target resolves through the model's names, the verified
    library sections' public symbols, or - for an inline COMDAT the model
    does not name (a header destructor) - a game object that emits that
    COMDAT byte-identically at the retail target (`library_code.GameComdats`).
    """
    from homm3.compare.canonicalize import normalize_anon_ns_name
    from homm3.verify.source_padding import eh_section
    if loaded is None:
        return 'unavailable', 'raw object missing or stale', None
    symbol = name
    if name.startswith('__h3cg$'):
        symbol = objects.compgen_symbol(unit, name) or name
    section = eh_section(loaded, symbol)
    if not section and '?%' in symbol:
        # An anonymous-namespace parent: the model spells retail's scope, the
        # object its own checkout path; both normalize to one identity.
        wanted = msvc_names.mask(normalize_anon_ns_name(symbol, unit))
        raw_names = {loaded[0].sym_name(idx) for idx, _v, sec in loaded[0].iter_symbols()
                     if sec > 0 and '?%' in loaded[0].sym_name(idx)}
        hits = [n for n in raw_names
                if msvc_names.mask(normalize_anon_ns_name(n, unit)) == wanted]
        if len(hits) == 1:
            section = eh_section(loaded, hits[0])
    if not section:
        return 'unavailable', 'no associative .text$x section for the parent', None
    obj = loaded[0]
    index = section['index']
    raw = obj.section_payload(index) or b''
    relocations = obj.typed_relocations(index)
    # A catch handler can sit inside its parent; the associative section
    # begins with the first cleanup outside the parent's own extent.
    parent_end = group.owner_rva + parent_size
    start = min([f for f in group.funclets if not group.owner_rva <= f < parent_end]
                + [group.stub])
    end = group.stub + 10
    if len(raw) != end - start:
        return 'mismatch', f'section is {len(raw)} bytes, retail group {end - start}', start
    retail = pe.read(start, end - start)
    covered = set()
    for offset in relocations:
        covered.update(range(offset, offset + 4))
    wrong = [i for i in range(len(raw)) if i not in covered and raw[i] != retail[i]]
    if wrong:
        return 'mismatch', f'{len(wrong)} byte(s) differ, first +{wrong[0]:#x}', start
    absolute = {offset for offset, (_t, kind) in relocations.items() if kind == DIR32}
    if {site - start for site in image.relocs_in(start, end)} != absolute:
        return 'mismatch', 'absolute relocation sites differ', start
    local = defaultdict(list)
    for idx, value, sec in obj.iter_symbols():
        if sec == index:
            local[obj.sym_name(idx)].append(value)
    xdata = {s['index'] for s in obj.section_table if s['name'] == '.xdata$x'}
    record = {obj.sym_name(idx) for idx, _value, sec in obj.iter_symbols() if sec in xdata}
    for offset, (target, kind) in sorted(relocations.items()):
        addend = struct.unpack_from('<i', raw, offset)[0]
        word = struct.unpack_from('<I', retail, offset)[0]
        if kind == REL32:
            actual = (start + offset + 4 + word) & 0xFFFFFFFF
            addend += 0
        elif kind == DIR32:
            actual = word - pe.image_base
        else:
            return 'unresolved', f'relocation type {kind} at +{offset:#x}', start
        if target in local:
            expected = {start + value for value in local[target]}
        elif target.startswith('$T') and target in record:
            expected = {group.funcinfo}
        else:
            keys = {msvc_names.mask(target), msvc_names.mask(normalize_anon_ns_name(target, unit))}
            expected = set()
            for key in keys:
                expected |= names.get((unit, key), set()) or names.get(('', key), set())
            if not expected and comdats is not None and comdats(target, actual - addend):
                expected = {actual - addend}
            if not expected:
                return 'unresolved', f'{target} has no retail address', start
        if actual - addend not in expected:
            return 'mismatch', f'+{offset:#x} {target} resolves elsewhere', start
    return 'exact', '', start


def funclet_verdicts(pe, model, objects, names, census, category, library_spans,
                     exact_parent=lambda unit, name: True):
    """{funclet rva: (verdict, parent rva, reason)} for every `eh-funclet` row.

    A differing group whose parent is not yet byte-exact is `pending-parent`:
    VC6 emits the funclets from the parent's frame layout, so they cannot be
    expected to agree before the parent does.
    """
    from homm3.delink.image import Image
    from homm3.verify.byte_accounting import verified_eh_groups, _covered
    from homm3.verify.library_code import GameComdats
    image = Image(pe)
    comdats = GameComdats(pe, census)
    _b, _h, rows = read(RETAIL / 'funclets.tsv')
    parent_of = {int(r['rva'], 16): int(r['parent_rva'], 16) for r in rows}
    out = {}
    for group, name, unit in verified_eh_groups(pe, model):
        verdict, reason, start = funclet_group(
            group, name, unit, objects.get(unit), objects, pe, image, names,
            census.get(group.owner_rva, 0), comdats)
        if verdict != 'exact' and not exact_parent(unit, name):
            verdict, reason = 'pending-parent', f'parent not byte-exact; {reason}'
        for funclet in group.funclets:
            if category.get(funclet) != 'eh-funclet':
                continue    # a catch handler inside its parent, not a census funclet
            if start is None or start <= funclet < group.stub:
                out[funclet] = (verdict, group.owner_rva, reason)
    for rva, cat in category.items():
        if cat != 'eh-funclet' or rva in out:
            continue
        parent = parent_of.get(rva, 0)
        if _covered(rva, rva + census[rva], library_spans):
            out[rva] = ('exact', parent, 'library contribution')
        elif category.get(parent) == 'runtime':
            out[rva] = ('unplaced', parent, 'library parent; no exact contribution holds it')
        else:
            out[rva] = ('unclaimed', parent, 'parent not claimed by a source unit')
    return out


# --------------------------------------------------- initializers, thunks --

def compare_initializers(pe, model, project, enrolled, library_names, census):
    """The byte-accounting comparisons that bind CRT bodies and import thunks."""
    from homm3.verify import import_thunks
    from homm3.verify.local_cleanups import compare as compare_cleanups
    from homm3.verify.shared_initializers import compare as compare_shared
    from homm3.verify.source_initializers import compare as compare_dynamic
    from homm3.verify.source_padding import Objects
    from homm3.verify.startup_bodies import compare as compare_startup
    dynamic = compare_dynamic(project, pe, model)
    startup = compare_startup(project, pe, model, enrolled)
    shared = compare_shared(project, pe, model, excluded={
        row['rva'] for row in startup['matches'] + dynamic['matches']},
        library_names=library_names)
    cleanups = compare_cleanups(project, pe, model, enrolled, Objects(project), library_names)
    claimed = {b.rva for b in model.functions if b.channel}
    thunks = import_thunks.compare(project, pe, census, claimed)
    return dict(dynamic=dynamic, startup=startup, shared=shared, cleanups=cleanups,
                thunks=thunks)


def initializer_verdicts(parts, census, category):
    """{rva: (verdict, owner, reason)} for every `init-thunk`/`import-thunk` row."""
    exact = {}
    for row in parts['dynamic']['matches']:
        exact[row['rva']] = (row['size'], f"{row['owner']['source']}:{row['owner']['name']}")
    for key in ('startup', 'shared', 'cleanups'):
        for row in parts[key]['matches'] + parts[key]['dependencies']:
            owner = row.get('unit') or row.get('source') or key
            exact.setdefault(row['rva'], (row['size'], f"{owner}:{row.get('symbol', key)}"))
    out = {}
    for rva, cat in category.items():
        if cat != 'init-thunk':
            continue
        if rva not in exact:
            out[rva] = ('unverified', '-', 'no source comparison binds this body')
        elif exact[rva][0] != census[rva]:
            out[rva] = ('mismatch', exact[rva][1],
                        f'compared {exact[rva][0]} bytes, census {census[rva]}')
        else:
            out[rva] = ('exact', exact[rva][1], '')
    matched = {r['rva']: f"{r['dll']}!{r['imported']}" for r in parts['thunks']['matches']}
    for rva, cat in category.items():
        if cat == 'import-thunk':
            out[rva] = (('exact', matched[rva], '') if rva in matched
                        else ('unverified', '-', 'no import directory/library proof'))
    return out


# ------------------------------------------------------------------ driver --

def measure(*, pe=None, model=None, verdicts=None, library_names=None, enrolled=None,
            parts=None):
    """(runtime rows, baseline rows) measured from the current tree.

    `homm3.verify.byte_accounting.report` passes the library verdicts and the
    initializer comparisons it has already made; standalone runs compute them.
    """
    from homm3.core.common import HOMM3_DIR
    from homm3.core.pe import image
    from homm3.core.project import Project
    from homm3.match import universe
    from homm3.model import resolve
    from homm3.verify.byte_accounting import library_verdicts, manifest_rows
    from homm3.verify.eh_records import _exact_functions
    from homm3.verify.source_padding import Objects
    pe = pe or image()
    model = model or resolve()
    category, census = universe.classify()
    if verdicts is None:
        verdicts, library_names = library_verdicts(pe, model)
    runtime = runtime_verdicts(pe, census, category, verdicts)
    library_spans = sorted((v.row.rva, v.row.rva + v.row.size) for v in verdicts
                           if v.verdict == 'exact' and v.row.kind in ('code', 'alias')
                           and v.row.library != 'zlib')
    project = Project(HOMM3_DIR)
    enrolled = manifest_rows() if enrolled is None else enrolled
    names = _names(model, enrolled, library_names)
    funclets = funclet_verdicts(pe, model, Objects(project), names, census, category,
                                library_spans, _exact_functions())
    if parts is None:
        parts = compare_initializers(pe, model, project, enrolled, library_names, census)
    others = initializer_verdicts(parts, census, category)
    baseline = []
    for rva in sorted(funclets):
        verdict, parent, reason = funclets[rva]
        baseline.append(dict(rva=f'{rva:#x}', size=str(census[rva]), category='eh-funclet',
                             owner=f'{parent:#x}', verdict=verdict, reason=reason or '-'))
    for rva in sorted(others):
        verdict, owner, reason = others[rva]
        baseline.append(dict(rva=f'{rva:#x}', size=str(census[rva]),
                             category=category[rva], owner=owner, verdict=verdict,
                             reason=reason or '-'))
    baseline.sort(key=lambda r: int(r['rva'], 16))
    return runtime, baseline


RUNTIME_HEADER = ['rva', 'size', 'name', 'library', 'member', 'sections', 'symbol', 'verdict']
BASELINE_HEADER = ['rva', 'size', 'category', 'owner', 'verdict', 'reason']


def _table(rows, header):
    return [[r[h] for h in header] for r in rows]


def committed():
    """{category: {rva of each banked `exact` row}} from the committed tables."""
    out = {}
    if RUNTIME_TABLE.is_file():
        out['runtime'] = {int(r['rva'], 16) for r in read(RUNTIME_TABLE)[2]
                          if r['verdict'] == 'exact'}
    if BASELINE.is_file():
        for r in read(BASELINE)[2]:
            exact = out.setdefault(r['category'], set())
            if r['verdict'] == 'exact':
                exact.add(int(r['rva'], 16))
    return out


def write_runtime(runtime):
    write(RUNTIME_TABLE, RUNTIME_BANNER, RUNTIME_HEADER, _table(runtime, RUNTIME_HEADER))


def write_baseline(baseline):
    write(BASELINE, BASELINE_BANNER, BASELINE_HEADER, _table(baseline, BASELINE_HEADER))


def stale(runtime, baseline):
    """Paths whose committed rows differ from the measured ones (None: unchecked)."""
    out = []
    for path, rows, header in ((RUNTIME_TABLE, runtime, RUNTIME_HEADER),
                               (BASELINE, baseline, BASELINE_HEADER)):
        if rows is None:
            continue
        current = read(path)[2] if path.is_file() else None
        if current != [{h: r[h] for h in header} for r in rows]:
            out.append(path)
    return out


def main(argv=None) -> int:
    import argparse
    parser = argparse.ArgumentParser(prog='homm3 verify generated-code', description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--write', action='store_true', help='rewrite both tables')
    parser.add_argument('--check', action='store_true', help='nonzero when a table is stale')
    parser.add_argument('--findings', action='store_true', help='list non-exact rows')
    args = parser.parse_args(argv)
    runtime, baseline = measure()
    tally = defaultdict(Counter)
    for r in runtime:
        tally['runtime'][r['verdict'].split(' ', 1)[0]] += 1
    for r in baseline:
        tally[r['category']][r['verdict']] += 1
    for cat in CATEGORIES:
        counts = tally.get(cat, Counter())
        total = sum(counts.values())
        detail = ', '.join(f'{k} {v}' for k, v in counts.most_common() if k != 'exact')
        print(f'{cat:13} {counts["exact"]:5} / {total:5} exact' + (f'  ({detail})' if detail else ''))
    if args.findings:
        for r in runtime:
            if r['verdict'] != 'exact':
                print(f"runtime {r['rva']} {r['name']}: {r['verdict']}")
        for r in baseline:
            if r['verdict'] != 'exact':
                print(f"{r['category']} {r['rva']} owner {r['owner']}: {r['verdict']} - {r['reason']}")
    if args.write:
        write_runtime(runtime)
        write_baseline(baseline)
        print(f'[generated-code] wrote {RUNTIME_TABLE.relative_to(ROOT)} and '
              f'{BASELINE.relative_to(ROOT)}')
    elif args.check:
        paths = stale(runtime, baseline)
        for path in paths:
            print(f'[generated-code] {path.relative_to(ROOT)} is stale; '
                  'run `homm3 verify generated-code --write`', file=sys.stderr)
        return 1 if paths else 0
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
