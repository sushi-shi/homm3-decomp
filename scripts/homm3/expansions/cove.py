"""Generate native Cove data from the pinned, attributed source definitions.

Run with --write after editing extensions/cove/definition.json; otherwise
verify that the checked-in C++ data is current. No downloads or game mutation.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
RESOURCES = ('wood', 'mercury', 'ore', 'sulfur', 'crystal', 'gems', 'gold')
BUILDINGS = {
    **{f'mageGuild{i + 1}': i for i in range(5)},
    'tavern': 5, 'shipyard': 6, 'fort': 7, 'citadel': 8, 'castle': 9,
    'villageHall': 10, 'townHall': 11, 'cityHall': 12, 'capitol': 13,
    'marketplace': 14, 'resourceSilo': 15, 'blacksmith': 16,
    'special1': 17, 'horde1': 18, 'horde1Upgr': 19, 'ship': 20,
    'special2': 21, 'special3': 22, 'special4': 23,
    'horde2': 24, 'horde2Upgr': 25, 'grail': 26,
    **{f'dwellingLvl{i + 1}': 30 + i for i in range(7)},
    **{f'dwellingUpLvl{i + 1}': 37 + i for i in range(7)},
    'dwellingUp2Lvl3': 44,
}
FLAGS = {
    'SHOOTER': 'creatureShootingArmy',
    'NO_MELEE_PENALTY': 'creatureNoMeleePenalty',
    'BLOCKS_RETALIATION': 'creatureFreeAttack',
    'SIEGE_WEAPON': 'creatureSiegeWeapon',
    'FLYING': 'creatureFlyingArmy',
}


def string(value):
    return json.dumps(value, ensure_ascii=True)


def resource_cost(cost):
    if set(cost) - set(RESOURCES):
        raise ValueError('unknown resource in cost')
    values = [cost.get(name, 0) for name in RESOURCES]
    if any(type(n) is not int or not 0 <= n <= 2147483647 for n in values):
        raise ValueError('invalid resource amount')
    return '{ ' + ', '.join(map(str, values)) + ' }'


def requirements(expression):
    if not expression:
        return []
    if isinstance(expression, str):
        return [BUILDINGS[expression]]
    if expression[0] == 'allOf':
        expression = expression[1:]
    elif any(item in ('anyOf', 'noneOf') for item in expression if isinstance(item, str)):
        raise ValueError('non-conjunctive building requirements need native logic')
    return [v for item in expression for v in requirements(item)]


def generate(data):
    roster = data['town']['creatures']
    if len(roster) != 7 or [len(row) for row in roster] != [2, 2, 3, 2, 2, 2, 2]:
        raise ValueError('unexpected Cove roster shape')
    names = ['cannon'] + [key for row in roster for key in row]
    if len(set(names)) != 16:
        raise ValueError('duplicate Cove creature')
    ids = {key: 150 + i for i, key in enumerate(names)}
    creatures = dict(data['creatures'], cannon=data['cannon'])
    result = [
        '// Generated by homm3.expansions.cove; do not edit.',
        '// Adapted from HotA Crew / VCMI Team, CC BY-SA 4.0.',
        '// Upstream commit: ' + data['provenance']['commit'],
        'static const Creature g_creatures[creatureCount] = {',
    ]
    animations = []
    for key in names:
        c = creatures[key]
        upgrades = c.get('upgrades', [])
        if len(upgrades) > 1 or any(name not in ids for name in upgrades):
            raise ValueError('unsupported upgrade graph')
        if key != 'cannon':
            tier = next(i for i, row in enumerate(roster) if key in row)
            stage = roster[tier].index(key)
            expected = roster[tier][stage + 1:stage + 2]
            if upgrades != expected or c['level'] != tier + 1:
                raise ValueError('roster disagrees with creature upgrade/level')
        flags = [] if key == 'cannon' else ['creatureAlive']
        if c.get('doubleWide'):
            flags.append('creatureDoubleWide')
        pending = []
        for ability in c.get('abilities', {}).values():
            kind = ability['type']
            if kind in FLAGS:
                flags.append(FLAGS[kind])
                if len(ability) > 1:
                    pending.append(kind + ':' + str(ability.get('subtype', 'parameters')))
            elif kind == 'KING' and ability.get('val', 0) in (0, 1, 2):
                flags.append('creatureKing' + str(ability.get('val', 0) + 1))
            else:
                pending.append(kind)
        graphics = c['graphics']
        sample = Path(next(iter(c['sound'].values()))).name[:4]
        wandering = c.get('advMapAmount', {'min': 0, 'max': 0})
        traits = [str(-1 if key == 'cannon' else 9), str(c['level'] - 1),
                  string(sample), string(Path(graphics['animation']).name),
                  ' | '.join(dict.fromkeys(flags)) or '0',
                  string(c['name']['singular']), string(c['name']['plural']), '0',
                  resource_cost(c['cost']), str(c['fightValue']), str(c['aiValue']),
                  str(c['growth']), str(c.get('horde', 0)), '{ 0, 0 }',
                  str(c['hitPoints']), str(c['speed']), str(c['attack']), str(c['defense']),
                  str(c['damage']['min']), str(c['damage']['max']), str(c.get('shots', 0)),
                  '0', str(wandering['min']), str(wandering['max'])]
        result.append('    { %s, %d, %d, { %s }, %s },' % (
            string(key), ids[key], ids[upgrades[0]] if upgrades else -1,
            ', '.join(traits), string(', '.join(sorted(set(pending))))))
        missile = graphics.get('missile', {})
        offsets = missile.get('offset', {})
        timing = graphics.get('animationTime', {})
        angles = missile.get('frameAngles', [])
        if len(angles) > 12:
            raise ValueError('too many missile angles')
        animations.append('    { { %s }, { %s }, 0, %d, %d, %d, %d, 115 },' % (
            ', '.join(str(offsets.get(k, 0)) for k in ('upperX', 'upperY', 'middleX', 'middleY', 'lowerX', 'lowerY')),
            ', '.join(f'{float(v):.1f}f' for v in angles + [0] * (12 - len(angles))),
            missile.get('attackClimaxFrame', 0),
            int(graphics.get('timeBetweenFidgets', 1) * 9000),
            int(timing.get('walk', 1) * 500), int(timing.get('attack', 1) * 500)))
    result += ['};', 'static const SMonFrameInfo g_animationTraits[creatureCount] = {',
               *animations, '};', 'static const Dwelling g_dwellings[dwellingCount] = {']
    for tier, row in enumerate(roster):
        for stage, key in enumerate(row):
            building = (f'dwellingLvl{tier + 1}' if stage == 0 else
                        f'dwellingUpLvl{tier + 1}' if stage == 1 else 'dwellingUp2Lvl3')
            b = data['buildings'][building]
            result.append('    { %d, %s, %d, %d, %d, %s },' % (
                BUILDINGS[building], string(b['name']), tier, stage, ids[key], resource_cost(b['cost'])))
    result += ['};', 'struct Building { int m_id; const char* m_name; const char* m_description; int m_cost[7]; __int64 m_requires; int m_upgrade; };',
               'static Building g_buildings[] = {']
    for key, b in data['buildings'].items():
        deps = requirements(b.get('requires'))
        upgrade = BUILDINGS.get(b.get('upgrades'), -1)
        if upgrade >= 0:
            deps.append(upgrade)
        mask = ' | '.join(f'(1i64 << {n})' for n in sorted(set(deps))) or '0'
        result.append('    { %d, %s, %s, %s, %s, %d },' % (
            BUILDINGS[key], string(b['name']), string(b['description']),
            resource_cost(b.get('cost') or {}), mask, upgrade))
    result += ['};']
    spell_ids = {name: int(number, 0) for name, number in re.findall(
        r"SPELL_([A-Z_]+) = (0x[0-9a-f]+|[0-9]+)", (ROOT / 'include/armygrp.h').read_text())}
    weights = [0] * 70
    for name, weight in data['town']['guildSpells'].items():
        name = re.sub(r'([a-z])([A-Z])', r'\1_\2', name).upper()
        name = name.replace('PROTECT_', 'PROTECTION_FROM_')
        weights[spell_ids[name]] = weight
    result += ['static const int g_coveSpellWeights[70] = { ' + ', '.join(map(str, weights)) + ' };']
    skills = 'pathfinding archery logistics scouting diplomacy navigation leadership wisdom mysticism luck ballistics eagleEye necromancy estates fireMagic airMagic waterMagic earthMagic scholar tactics artillery learning offence armorer intelligence sorcery resistance firstAid'.split()
    towns = 'castle rampart tower inferno necropolis dungeon stronghold fortress conflux cove'.split()
    primary = 'attack defence spellpower knowledge'.split()
    array = lambda values: '{ ' + ', '.join(map(str, values)) + ' }'
    result += ['static const THeroClassTraits g_coveClasses[2] = {']
    for key in ('captain', 'navigator'):
        c = data['heroClasses'][key]
        result.append('    { 9, %s, 1.0f, %s, %s, %s, %s, %s, { 0, 0 } },' % (
            string(c['name']), array(c['primarySkills'][k] for k in primary),
            array(c['lowLevelChance'][k] for k in primary), array(c['highLevelChance'][k] for k in primary),
            array(c['secondarySkills'][k] for k in skills), array(c['tavern'][k] for k in towns)))
    spells = {'slow': 54, 'cure': 37, 'forgetfulness': 61, 'dispel': 35, 'airShield': 28, 'clone': 65, 'fireball': 21, 'bless': 41}
    result += ['};', 'static const THeroTraits g_coveHeroes[20] = {']
    biographies = []
    specialties = []
    for index, (key, h) in enumerate(data['heroes'].items()):
        hero_id = 163 + index
        skill = [(skills.index(v['skill']), ('none', 'basic', 'advanced', 'expert').index(v['level'])) for v in h['skills']]
        skill += [(-1, 0)] * (2 - len(skill))
        army = h['army']
        if len(army) != 3 or len(skill) != 2:
            raise ValueError('unsupported initial hero army or skills')
        spellbook = h.get('spellbook', [])
        result.append('    { %d, 0, THeroClass(%d), %d, %d, %d, %d, %d, { 0, 0, 0 }, %d, %s, %s, %s, %s, %s, { %d }, { 0, 0, 0, 0 }, %s, %s },' % (
            int(h.get('female', False)), 18 if h['class'] == 'captain' else 19,
            *skill[0], *skill[1], bool(spellbook), spells[spellbook[0]] if spellbook else -1,
            *(f'TCreatureType({ids[v["creature"].split(":")[-1]]})' for v in army),
            string(f'HPS{hero_id}CV.pcx'), string(f'HPL{hero_id}CV.pcx'),
            257 | (65536 if h.get('special') else 0), string(h['texts']['name']),
            ', '.join(str(v[k]) for v in army for k in ('min', 'max'))))
        biographies.append(string(h['texts']['biography']))
        spec = h['specialty']
        kind, subject, alternate, target = -1, -1, -1, -1
        if 'creature' in spec:
            kind, subject = 1, ids[spec['creature'].split(':')[-1]]
        elif 'secondary' in spec:
            kind, subject = 0, skills.index(spec['secondary'])
        elif spec.get('base', {}).get('type') == 'SPECIAL_UPGRADE':
            kind, subject, alternate, target = 6, ids['pirate'], ids['corsair'], ids['seadog']
        else:
            for bonus in spec.get('bonuses', {}).values():
                if bonus['type'] == 'GENERATE_RESOURCE':
                    kind, subject = 2, RESOURCES.index(bonus['subtype'].split('.')[-1])
                elif bonus['type'] == 'MOVEMENT':
                    kind, subject = 8, skills.index('navigation')
                elif bonus['type'] == 'SIGHT_RADIUS':
                    kind, subject = 9, skills.index('scouting')
                elif bonus['type'] == 'SPELL_DURATION':
                    kind, subject = 10, spells['forgetfulness']
                elif bonus['type'] == 'SPELL' and bonus['subtype'] == 'spell.specialClone':
                    kind, subject = 11, spells['clone']
                elif bonus['type'] in ('SPECIAL_SPELL_LEV', 'SPECIAL_PECULIAR_ENCHANT'):
                    kind, subject = 3, spells[bonus['subtype'].split('.')[-1]]
        text = h['texts']['specialty']
        specialties.append('    { %d, { %d }, 0, 0, 0, TCreatureType(%d), TCreatureType(%d), %s, %s, %s },' % (
            kind, subject, alternate, target, string(text['name']), string(text['tooltip']), string(text['description'])))
    result += ['};', 'static const char* const g_coveBiographies[20] = {', '    ' + ',\n    '.join(biographies), '};',
               'static const THeroSpecificAbility g_coveSpecialties[20] = {', *specialties, '};',
               'static const char* const g_coveTownNames[16] = {', '    ' + ', '.join(map(string, data['town']['names'])), '};', '']
    return '\n'.join(result)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args(argv)
    data = json.loads((ROOT / 'extensions/cove/definition.json').read_text())
    output = generate(data)
    path = ROOT / 'src/cove_data.inc'
    if args.write:
        path.write_text(output)
    elif not path.is_file() or path.read_text() != output:
        parser.error('Cove data is stale; run with --write')
    print('Cove native data: 15 recruits, Cannon, 15 dwellings, 39 buildings')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
