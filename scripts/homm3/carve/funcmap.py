#!/usr/bin/env python3
"""homm3.carve.funcmap - admit the function-map tables the synth PDB needs.

The synth-PDB/delink phase requires a total per-function name map of the
image. Approved architecture (decision log 2026-08-04), four sources of
truth by who owns the names:

  1. GAME code:      the `RVA(rva, size)` macros in src/ ARE the map -
                     source is the authority, re-derived every build by the
                     label-map generator (later phase, P5.2). No config
                     table exists for game code, by design.
  2. zlib:           statically linked but never reconstructed from src/
                     (vendored sources stay pristine) ->
                     config/retail-zlib-map.tsv, emitted here. The only
                     such library in the image - the DNA verdict rules out
                     MFC and any other static middleware.
  3. CRT/C++ runtime: functions we NAME but do not match ->
                     config/retail-runtime-map.tsv, emitted here. Raw
                     linker symbol where the masked-archive channel proved
                     it against retail bytes; working label otherwise.
                     Rows get properly mapped as matching proceeds.
  4. the universe:   config/retail-functions.tsv (admitted earlier,
                     hand-owned) - every function in the executable;
                     "still unmatched" is a set difference against the
                     three sources above, computed by later tooling.

Eventually these feed the gruntz-style README coverage table; functions not
written directly in code (EH funclets, init/cleanup thunks, runtime
library, import thunks) are excluded there, derivable from the tiers in
evidence/retail-symbols.csv.

ADMISSION: both tables are hand-owned after generation (the
MANUALLY MANAGED stamp); the stage refuses to overwrite them unless
--force is given.
"""
from __future__ import annotations

import csv
import sys

from homm3.carve import common

ZLIB_OUT = common.HOMM3_DIR / "config/retail-zlib-map.tsv"
RUNTIME_OUT = common.HOMM3_DIR / "config/retail-runtime-map.tsv"
SYMBOLS = common.EVIDENCE_DIR / "retail-symbols.csv"

RUNTIME_BANDS = {"crt-libcmt", "cxx-libcpmt"}
ZLIB_BYTES = 24027  # band-map reconciliation (docs/exe-dna.md)

STAMP = ("# MANUALLY MANAGED - INITIALLY GENERATED by `python3 -m "
         "homm3.carve funcmap`\n# (provenance below) and hand-owned after "
         "admission: corrections are edited\n# directly into these rows; "
         "do not regenerate over hand edits.\n")


def main(argv=None) -> int:
    argv = list(argv or [])
    force = "--force" in argv
    for target in (ZLIB_OUT, RUNTIME_OUT):
        if target.is_file() and not force:
            common.die(f"{target} already exists and is hand-owned - "
                       "rerun with --force only if you mean to regenerate")

    with SYMBOLS.open() as fh:
        rows = list(csv.DictReader(
            line for line in fh if not line.startswith("#")))

    zlib, runtime = [], []
    for r in rows:
        rva, band = int(r["rva"], 16), r["library"]
        if band == "zlib":
            zlib.append((rva, int(r["size"]), r["symbol"] or r["name"]))
        elif band in RUNTIME_BANDS:
            runtime.append((rva, r["symbol"] or r["name"]))

    zlib.sort()
    runtime.sort()
    if sum(s for _r, s, _n in zlib) != ZLIB_BYTES:
        common.die(f"zlib map: {sum(s for _r, s, _n in zlib)} B, expected "
                   f"{ZLIB_BYTES} - band map moved, review before admitting")
    for label, table in (("zlib", zlib), ("runtime", runtime)):
        names = [t[-1] for t in table]
        if not table or len(set(names)) != len(names):
            common.die(f"{label} map: empty or duplicate names")

    def write(path, header, table, note):
        path.write_text(
            STAMP
            + "\n".join(common.provenance("homm3.carve.funcmap")) + "\n"
            + note
            + "\t".join(header) + "\n"
            + "\n".join("\t".join(str(c) for c in
                                  (f"0x{row[0]:x}",) + row[1:])
                        for row in table) + "\n")

    write(ZLIB_OUT, ["rva", "size", "name"], zlib,
          "# zlib 1.1.3, statically linked, never reconstructed from src/\n"
          "# (vendored sources stay pristine): the reviewed rva->symbol map\n"
          "# promised by CLAUDE.md/P0.2. Raw symbol where the recompiled-\n"
          "# object channel proved it; working label for zlib's static\n"
          "# internals until matching completes them.\n")
    write(RUNTIME_OUT, ["rva", "name"], runtime,
          "# CRT (LIBCMT) + C++ runtime (LIBCPMT) bands: functions we NAME\n"
          "# but do not match from source. Raw linker symbol where the\n"
          "# masked-archive channel proved it against retail bytes; working\n"
          "# label otherwise. Rows get properly mapped as matching\n"
          "# proceeds. MFC is absent from the image (docs/exe-dna.md).\n")

    proven = sum(1 for _r, n in runtime if n.startswith(("?", "_", "@")))
    zproven = sum(1 for _r, _s, n in zlib if n.startswith(("?", "_", "@")))
    print(f"[carve funcmap] zlib: {len(zlib)} functions "
          f"({zproven} proven symbols) -> {ZLIB_OUT.name}")
    print(f"[carve funcmap] crt+cxx runtime: {len(runtime)} functions "
          f"({proven} proven symbols) -> {RUNTIME_OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
