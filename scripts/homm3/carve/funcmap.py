#!/usr/bin/env python3
"""homm3.carve.funcmap - admit the function mappings the delinker needs.

Prerequisite for synth-PDB generation + delinking (vostok): a per-function
name map of the image, admitted into config/. Two tables, per the approved
split:

  config/retail-function-map.tsv   rva, size, name - every function in the
                                   GAME and ZLIB bands, named by the naming
                                   layer (unique, valid C identifiers;
                                   tier/confidence stay in
                                   evidence/retail-symbols.csv - this table
                                   is the flat map, not the evidence).
  config/retail-runtime-map.tsv    rva, name - every function in the
                                   CRT (LIBCMT) and C++ runtime (LIBCPMT)
                                   bands, including LIBCPMT's funclet band.
                                   Where the DNA pass proved the original
                                   linker symbol against retail bytes, the
                                   RAW SYMBOL is the name (what a synth PDB
                                   wants); otherwise the working label.

MFC is absent from the image (three-channel verdict, docs/exe-dna.md), so
there is no MFC table to emit: the two mfc-pattern hits are 8-byte generic
EH stubs in game space (`-island`, attribution unproven) and ride in the
game map under their working labels.

ADMISSION: both tables are hand-owned after generation (the
MANUALLY MANAGED stamp); the stage refuses to overwrite them unless
--force is given.
"""
from __future__ import annotations

import csv
import sys

from homm3.carve import common

GAME_OUT = common.HOMM3_DIR / "config/retail-function-map.tsv"
RUNTIME_OUT = common.HOMM3_DIR / "config/retail-runtime-map.tsv"
SYMBOLS = common.EVIDENCE_DIR / "retail-symbols.csv"

GAME_BANDS = {"game", "zlib"}
RUNTIME_BANDS = {"crt-libcmt", "cxx-libcpmt"}

STAMP = ("# MANUALLY MANAGED - INITIALLY GENERATED by `python3 -m "
         "homm3.carve funcmap`\n# (provenance below) and hand-owned after "
         "admission: corrections are edited\n# directly into these rows; "
         "do not regenerate over hand edits.\n")


def main(argv=None) -> int:
    argv = list(argv or [])
    force = "--force" in argv
    for target in (GAME_OUT, RUNTIME_OUT):
        if target.is_file() and not force:
            common.die(f"{target} already exists and is hand-owned - "
                       "rerun with --force only if you mean to regenerate")

    with SYMBOLS.open() as fh:
        rows = list(csv.DictReader(
            line for line in fh if not line.startswith("#")))

    game, runtime = [], []
    for r in rows:
        rva, band = int(r["rva"], 16), r["library"]
        if band in GAME_BANDS:
            game.append((rva, int(r["size"]), r["name"]))
        elif band in RUNTIME_BANDS:
            runtime.append((rva, r["symbol"] or r["name"]))

    game.sort()
    runtime.sort()
    for label, table, width in (("game", game, 3), ("runtime", runtime, 2)):
        names = [t[-1] for t in table]
        if len(set(names)) != len(names):
            common.die(f"{label} map: duplicate names - naming layer defect")
        if not table:
            common.die(f"{label} map: empty selection")

    def write(path, header, table):
        path.write_text(
            STAMP
            + "\n".join(common.provenance("homm3.carve.funcmap")) + "\n"
            + "\t".join(header) + "\n"
            + "\n".join("\t".join(str(c) for c in
                                  (f"0x{row[0]:x}",) + row[1:])
                        for row in table) + "\n")

    write(GAME_OUT, ["rva", "size", "name"], game)
    write(RUNTIME_OUT, ["rva", "name"], runtime)

    proven = sum(1 for _rva, name in runtime
                 if name.startswith(("?", "_", "@")))
    print(f"[carve funcmap] game+zlib: {len(game)} functions "
          f"({sum(s for _r, s, _n in game):,} B) -> {GAME_OUT.name}")
    print(f"[carve funcmap] crt+cxx runtime: {len(runtime)} functions "
          f"({proven} with retail-proven linker symbols) "
          f"-> {RUNTIME_OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
