#!/usr/bin/env python3
"""homm3.carve.common - paths, target intake gate, and TSV conventions.

Everything downstream keys off one pinned image, so intake is a HARD gate: any
byte deviation from the recorded sha256/size aborts every stage. Game bytes are
never copied into the repo - the exe is referenced in place ($HOMM3_EXE, then
../orig/, then ../decomp-attempt-1/build/orig/) and only a fingerprint stamp
(target.json) lands under gitignored build/carve/.

TSV convention shared by all stages: `#` provenance lines (generator, exe sha,
date), then a tab-separated header, then rows. RVAs are 0x%x, sizes decimal.
"""
from __future__ import annotations

import datetime
import hashlib
import json
import os
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
HOMM3_DIR = Path(os.environ.get("HOMM3_DIR") or next(
    (p for p in SCRIPT_DIR.parents if (p / "flake.nix").exists()), SCRIPT_DIR))
CARVE_DIR = HOMM3_DIR / "build/carve"
TARGET_JSON = CARVE_DIR / "target.json"

TARGET_SHA256 = "057c9d88e7206f6669a4615de2c6e02ab6c4e2d570a9e2badf07fe0bd6247274"
TARGET_SIZE = 2732032
IMAGE_BASE = 0x400000

EXE_CANDIDATES = [
    HOMM3_DIR / "../orig/HEROES3.EXE",
    HOMM3_DIR / "../decomp-attempt-1/build/orig/HEROES3.EXE",
]


def die(msg: str) -> None:
    print(f"[carve] ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def sha256_of(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def resolve_exe() -> Path:
    env = os.environ.get("HOMM3_EXE")
    candidates = ([Path(env)] if env else []) + EXE_CANDIDATES
    for cand in candidates:
        if cand.is_file():
            return cand.resolve()
    die("HEROES3.EXE not found; set $HOMM3_EXE or place it at ../orig/")


def gate_exe(path: Path) -> dict:
    """The hard gate: refuse to analyze anything but the pinned pressing."""
    size = path.stat().st_size
    if size != TARGET_SIZE:
        die(f"{path}: size {size} != pinned {TARGET_SIZE}")
    sha = sha256_of(path)
    if sha != TARGET_SHA256:
        die(f"{path}: sha256 {sha} != pinned {TARGET_SHA256}")
    return {"path": str(path), "sha256": sha, "size": size,
            "image_base": IMAGE_BASE}


SANITIZED_EXE = CARVE_DIR / "HEROES3.llvm-objdump.exe"
_LOAD_CONFIG_INDEX = 10


def sanitized_exe(gated_path: Path) -> Path:
    """A working copy llvm-objdump will accept, under gitignored build/carve/.

    The retail linker put the load-config directory at RVA 0x2a0 - inside the
    PE headers, below the first section - and llvm-objdump 21 refuses to open
    such an image at all. The copy differs from retail in exactly the 8 bytes
    of data-directory[10] (zeroed); every RVA, section and code byte is
    identical, so it is valid ONLY as a disassembly substrate, never as
    evidence. Callers must pass an already sha-gated path.
    """
    data = bytearray(gated_path.read_bytes())
    pe = int.from_bytes(data[0x3C:0x40], "little")
    entry = pe + 24 + 96 + _LOAD_CONFIG_INDEX * 8
    data[entry:entry + 8] = b"\0" * 8
    CARVE_DIR.mkdir(parents=True, exist_ok=True)
    if not (SANITIZED_EXE.is_file() and SANITIZED_EXE.read_bytes() == bytes(data)):
        SANITIZED_EXE.write_bytes(bytes(data))
    return SANITIZED_EXE


def intake() -> dict:
    """S0: resolve + gate the exe, stamp target.json. Idempotent; every stage
    calls this so no stage can run against an unpinned image."""
    exe = resolve_exe()
    info = gate_exe(exe)
    from homm3.carve.find_relocs import Image
    image = Image(str(exe))
    info["sections"] = [
        {"name": s.name, "rva": s.rva, "size": s.size, "mapped": s.mapped,
         "raw_offset": s.raw_offset, "executable": s.executable}
        for s in image.sections]
    info["generated"] = datetime.date.today().isoformat()
    CARVE_DIR.mkdir(parents=True, exist_ok=True)
    TARGET_JSON.write_text(json.dumps(info, indent=2) + "\n")
    return info


def load_image():
    """The vendored PE reader over the gated exe - the package's only one.

    Reads the sanitized working copy (see sanitized_exe) so the vendored
    code_sites channel can shell out to llvm-objdump on image.path."""
    from homm3.carve.find_relocs import Image
    info = intake()
    work = sanitized_exe(Path(info["path"]))
    info["sanitized_path"] = str(work)
    return Image(str(work)), info


MANUAL_BANNER = (
    "# MANUALLY MANAGED - this file was INITIALLY GENERATED by homm3.carve\n"
    "# (provenance below) and is hand-owned after admission: boundary\n"
    "# corrections are edited directly into these rows; do not regenerate\n"
    "# over hand edits.\n")


def provenance(generator: str, extra: list[str] | None = None) -> list[str]:
    lines = [
        f"# generator: {generator}",
        f"# exe: HEROES3.EXE sha256={TARGET_SHA256} size={TARGET_SIZE}",
        f"# date: {datetime.date.today().isoformat()}",
        "# ANALYSIS OUTPUT, NOT RETAIL EVIDENCE",
    ]
    return lines + list(extra or [])


def write_tsv(path: Path, generator: str, header: list[str], rows,
              extra: list[str] | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w") as fh:
        for line in provenance(generator, extra):
            fh.write(line + "\n")
        fh.write("\t".join(header) + "\n")
        for row in rows:
            fh.write("\t".join(str(cell) for cell in row) + "\n")
    return path


def read_tsv(path: Path) -> list[dict]:
    """Rows as dicts; `#` lines and blanks skipped; first data line is the header."""
    header = None
    rows = []
    for line in Path(path).read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        cells = line.split("\t")
        if header is None:
            header = cells
            continue
        rows.append(dict(zip(header, cells)))
    if header is None:
        die(f"{path}: empty TSV")
    return rows


def need(path: Path, stage: str) -> Path:
    if not Path(path).is_file():
        die(f"missing {path} - run `python3 -m homm3.carve {stage}` first")
    return path
